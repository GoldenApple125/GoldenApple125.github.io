function loadSave() {
    var raw = null;
    try { raw = window.localStorage.getItem(SAVE_KEY); } catch (e) { raw = null; }
    if (!raw) return defaultSave();
    var data;
    try { data = JSON.parse(raw); } catch (e) { return defaultSave(); }
    if (!data || data.version !== 1) return defaultSave();
    var d = defaultSave();
    for (var k in d) { if (!(k in data)) data[k] = d[k]; }
    /* ⚠️ 老存档迁移：`0.1.1` 之前的存档**没有 `cleared`**（逐关通关记录），
     *    只有累计的 `clears`。直接给个空数组会让老玩家**前面的关全部变回未通关**
     *    （选关界面会出现"第 1 关没通过、第 2 关锁着"的倒退）。
     *    这里按原设计的"顺序解锁"尽力还原：累计通了 N 次，就当**前 N 关**都通过过。
     *    （它不一定精确 —— 但只会**多**解锁，不会把已有进度抹掉，方向是安全的。）
     *
     * ⚠️⚠️ 这里**不能引用 `LEVELS`**：本函数在文件末尾就被调用（`var Save = loadSave()`），
     *    而 `LEVELS` 定义在**后加载**的 `level.js` 里 → 一跑就 `ReferenceError`
     *    （实测踩过：异常被外层 try 吞掉，迁移静默失效）。
     *    多出来的下标没有副作用 —— `levelUnlocked()` 只关心存在的关卡。 */
    if (!Array.isArray(data.cleared)) {
        data.cleared = [];
        var n = Math.max(0, Number(data.clears) || 0);
        for (var i = 0; i < n; i++) data.cleared[i] = true;
    }
    /* ⚠️ 老存档迁移：`0.1.1` 之前的存档**没有 `purchasedPassives`**（被动那时候是免费的），
     *    直接给空数组会让老玩家的被动**全部变回未购买** —— 出战配置里的被动被清空、
     *    还得重花金币买回来，等于**把已有的东西收走**。
     *    ⇒ 老存档一律**视为六个被动全都已买**（方向是安全的：只会多给，不会收走）。
     *    ⚠️ 判断依据是"**这个字段在不在存档里**"（注意是 `data` 不是 `d`，
     *       `d` 是刚生成的默认档，它一定没有这个字段 → 写成 `d` 会永远走迁移分支，
     *       新玩家也白送六个被动）。 */
    if (!Array.isArray(data.purchasedPassives)) {
        data.purchasedPassives = [];
        for (var pi = 0; pi < PASSIVES.length; pi++) data.purchasedPassives.push(pi);
    }
    /* ⚠️ 技能槽上限的**兜底下限**（`0.2.0` 加，`0.2.1` 跟着起点降到 **2**）。
     *
     * 历史：`0.2.0` 中途一度把它提到 **4**（为了让第 4 个主动「激光」一解锁就装得上），
     *    用户随后定为"**初始 3 个槽**"；`0.2.1` 又收到"**基础技能槽改成 2**"。
     *    ⇒ 现在默认 `maxActive: 2`，这个下限也是 **2**。
     *    ⚠️ 当年那段"3 → 4"的迁移**必须一起改掉**：它会把**每一个**老存档
     *      强行拉到 4（`>= 4` 才不迁移），于是"初始 2 槽"对老玩家根本不生效。
     *      现在下限是 2、默认也是 2 ⇒ 谁都不需要被迁移。
     *
     * ⚠️ 迁移方向仍然是**只升不降**（`< 2` 才拉到 2）：
     *    不能写成 `= 2` —— 那会把玩家**花金币买到 3 / 4 槽**的进度**抹掉**。
     *    ⇒ 老存档保持它自己的槽数，新开档才是 2。这正是"改默认值，不改存量"。
     *    ⚠️ 副作用：老存档可能**比新上限（`MAX_ACTIVE_SLOTS` = 4）还多**
     *      ⇒ 两处兜底（`cds` 长度取 `max()`、商店显示取 `min()`），见各自的说明。
     * ⚠️ 用 `data.maxActive` 判断，不要用 `d.maxActive`：
     *    `d` 是刚生成的默认档（永远是 2），拿它判会**永远走迁移分支**
     *    （与上面 `purchasedPassives` 那条同一个坑）。
     * ⚠️⚠️ 两个下限 `ACTIVE_SLOTS_MIN` / `PASSIVE_SLOTS_MIN` 现在定义在**模块顶部**
     *    （挨着 `SAVE_KEY`）：商店算"已买几档"（`ui.js`）与测试都要读它们，
     *    写成这里的局部变量会让那两处直接 `ReferenceError`（实测踩过）。 */
    if (!(Number(data.maxActive) >= ACTIVE_SLOTS_MIN)) data.maxActive = ACTIVE_SLOTS_MIN;
    /* ⭐⭐ **上限也夹一次**（`0.3.0`，用户 2026-10-02："现在技能槽上限是 4，没有数字 5"）。
     *
     * ⚠️ 背景：上面那条迁移是"**只升不降**"（为了让玩家买到的槽不被抹掉 ✔），
     *    于是 `0.2.1` 之前买满 **5** 槽的老存档会**永远留着 5** ✗ ⇒
     *    底部 HUD 多出第 5 格、按键数字显示 `5` ✗（而上限早就收到 4 了）。
     * ⇒ **下限只升不降、上限必须夹死**：买到的 3/4 槽留着 ✔，超上限的旧值收回来 ✔。
     * ⚠️ 之前只在两处"读的时候"兜底（`cds` 长度取 `max()`、商店显示取 `min()`）⇒
     *    HUD 建槽用的是 `Save.maxActive` 本身 ✗ ⇒ 它才是漏网的那一处 ✔。 */
    if (Number(data.maxActive) > MAX_ACTIVE_SLOTS) data.maxActive = MAX_ACTIVE_SLOTS;
    /* ⭐ **饰品槽的兜底下限**（`0.2.1` 补）：与技能槽同一条规矩 —— 默认数见 `PASSIVE_SLOTS_MIN`（`0.3.1` 起是 **1** ✗）、只升不降。
     *    ⚠️ 原来这里**只**兜技能槽，饰品槽靠模板里的 `maxPassive: 3` 保证；
     *      而价格下标 = `Save.maxPassive - PASSIVE_SLOTS_MIN` ⇒ 下限必须是明确的一处
     *      （否则下标可能算成负数）。 */
    if (!(Number(data.maxPassive) >= PASSIVE_SLOTS_MIN)) data.maxPassive = PASSIVE_SLOTS_MIN;
    return data;
}

