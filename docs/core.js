var LOGICAL_H = 720;

/* ⭐ 网格单位（`0.1.1` 缩格子：`TILE` 80 → 40，网格 16×9 → 32×18）
 *
 * ⚠️⚠️ 这三个数**互相咬死**，改一个必须重算另外两个：
 *    `TILE × COLS = LOGICAL_W`、`TILE × ROWS = LOGICAL_H`
 *    ⇒ `TILE` 必须是**同时整除 1280 与 720** 的值。可选只有 40 / 20 / 16 / 10 / 8 / 5 …
 *      其中 20 已经比玩家（28px）还窄、一格装不下一个角色 ⇒ 实际可用的就是 **40**。
 *      曾经想试 `TILE=64`（整除 1280，20 列）—— **720/64 = 11.25 不整除，直接排除**。
 *
 * ⚠️ `PIXEL` 的含义要说清（它**不再**是"绘制取整单位"，那个角色已交给 `ART`）：
 *    它现在只负责一件事 —— **让 `TILE` 的来源一眼可查**（`PIXEL × 20 = TILE`），
 *    外加"格子线画多细"这种纯视觉用途。绘制取整一律走 `ART`（见下）。
 *
 * ⭐ `ART` = **绘制取整单位**（所有实体绘制坐标/尺寸都取整到它的倍数）。
 *
 * ⚠️⚠️ **`0.2.0` 从 2 改成 1**，理由是**移动流畅度**（用户原话："确保敌人移动和位置
 *    与玩家一样有流畅的过渡"）。实测逐帧步长（`round(pos/ART)*ART - half` 的差）：
 *
 *     | 取整单位 | 玩家 speed 3 | 敌人 speed 1.0（实测 0.745） |
 *     |---|---|---|
 *     | **2（旧）** | `4,2,4,2…`（停 0 帧） | **`2,0,2,0…`（停 7/15 帧）** |
 *     | **1（现）** | `3,3,3,3…`（停 0 帧） | **`1,1,1,1…`（停 0 帧）** |
 *
 *    根本原因：**敌人每帧只走 0.5 逻辑像素 < 取整单位 2** ⇒ 画出来的左缘
 *    "隔一帧才动一次、且一次跳 2" ⇒ 画面上**一顿一顿**。
 *    玩家速度是 3（取整单位的 1.5 倍），同样取整却看不出台阶 ——
 *    这正解释了为什么只有敌人被反馈"不流畅"。
 *
 *    取 1（= 逐逻辑像素）后：**没有任何实体的每帧位移小于取整单位**，
 *    于是"每帧都动、且每帧动得均匀"，与玩家一致。
 *
 * ⚠️ 为什么不用"亚像素"（干脆不取整）：canvas 内部分辨率就是 1280×720、
 *    **没有缩放变换**（`imageSmoothingEnabled = false` 只管图片、不管图形），
 *    所以非整数坐标的方块边缘会被抗锯齿**糊掉**。取整到 1 逻辑像素既清晰又够顺。
 * ⚠️ `ART` 必须能整除 `TILE`（40/1 = 40 ✓），否则格子线会与实体错开半格。
 * ⚠️ 若**将来**出现比"1 逻辑像素/帧"更慢的实体，同样的问题会再出现 ——
 *    那时要么提它的速度，要么改成"亚像素绘制 + 整体 2× 放大"，别只调 `ART`。
 *
 * ⚠️ 缩格子的**代价与做法**写在 level.js 的地图数据上面：旧地图按 2×2 机械展开，
 *    世界几何一个像素都没变（所以碰撞测试场那些"缝宽 20/28/44"的约束仍然成立）。 */
