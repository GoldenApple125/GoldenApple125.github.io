var TILE_FALLBACK = '.';

/* id → 类型（`solidCells` 与渲染用；启动时建一次） */
var TILE_TYPES_BY_ID = {};
(function () {
    for (var ch in TILE_TYPES) {
        if (Object.prototype.hasOwnProperty.call(TILE_TYPES, ch)) {
            TILE_TYPES_BY_ID[TILE_TYPES[ch].id] = TILE_TYPES[ch];
        }
    }
}());

/* 字符 → 类型（找不到就用兜底）。⚠️ 只在解析时查，热路径不要调。 */
function tileTypeOf(ch) {
    return TILE_TYPES[ch] || TILE_TYPES[TILE_FALLBACK];
}

/* ⭐⭐ **解析地图**（`0.3.0` 起返回**完整网格**，不再只返回 `#` 的坐标）
 * 返回 `{ cols, rows, ids, chars }`：
 *   · `chars` —— 原始字符网格（校验器 / 工具用，保留"作者写了什么"）
 *   · `ids`   —— 类型 id 的二维数组（`floor` / `wall` / 以后的别的）
 * ⚠️ 行短了按 `TILE_FALLBACK` 补、行多了截断 —— 越界由 `verify-levels` 报，
 *    这里**不抛异常**（不能因为一张图写错就让整局起不来）。
 * ⚠️ 与旧 `parseMap` 的**行为差异只有一处**：空地现在也在网格里（旧版直接忽略它）。 */
function parseTiles(rows) {
    var r, c, line, ids = [], chars = [];
    for (r = 0; r < ROWS; r++) {
        line = rows[r] || '';
        var rowIds = [], rowCh = '';
        for (c = 0; c < COLS; c++) {
            var ch = (c < line.length) ? line.charAt(c) : TILE_FALLBACK;
            rowCh += ch;
            rowIds.push(tileTypeOf(ch).id);
        }
        ids.push(rowIds);
        chars.push(rowCh);
    }
    return { cols: COLS, rows: ROWS, ids: ids, chars: chars };
}

/* ⭐ **挡路的格子**（`[col,row]` 列表）—— 刷怪、测试与 `obstacles()` 共用。
 * ⚠️ 判据是**类型表里的 `solid`**，不是"字符是不是 `#`" ⇒ 以后加一种墙不用改这里。 */
function solidCells(map) {
    var g = map.tiles, out = [], r, c;
    if (!g) return out;
    for (r = 0; r < g.rows; r++) {
        for (c = 0; c < g.cols; c++) {
            var t = TILE_TYPES_BY_ID[g.ids[r][c]];
            if (t && t.solid) out.push([c, r]);
        }
    }
    return out;
}

