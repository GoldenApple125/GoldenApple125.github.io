/* ============ 幽灵碰撞哨兵（运行时每帧检查） ============
 * 碰撞体是**方形（AABB）**，与画出来的方块一致 —— 见 collision.js 顶部的说明。
 *
 * 三个**互相独立**的指标，不要混为一谈：
 *  ① `tunnel` 穿墙：**玩家与障碍**的残留重叠 > TOL_WALL
 *     —— separateFromRects 保证"推完即刚好相切（只留 0.01 微余量）"，
 *        所以超过 0.75 就说明分离失败 = 穿墙。**这是严格指标。**
 *  ② `crush` 被挤压：**玩家与敌人**的残留重叠 > TOL_ENEMY
 *     —— 敌人在主动挤压，物理上必然有残留（实测极端场景峰值 8.54）。
 *        这只用来报警"异常"，不是"越小越好"。
 *  ③ `ghost` 幽灵碰撞：**几何上没重叠，却连续多帧动不了** ⇒ 位移被吃掉。
 *     （这是用户试玩才发现的**旧盲区**：原指标只看"有没有重叠"，
 *      而这类问题是"位置合法但走不动"。碰撞函数本身没错，错在调用方式。）
 *  ④ `cross` 假阳性：几何上分离却报碰撞 ⇒ 判定与几何不符。
 * 另：`maxSpeed` 记录本局最高速度，用于判断是否存在隧穿风险。
 */
var COLCHECK = {
    log: [],
    counts: { cross: 0, tunnel: 0, crush: 0, ghost: 0, checks: 0 },    TOL_WALL: 0.75,          // ① 玩家↔障碍：严格（分离保证"推完即分离"）
    TOL_ENEMY: 15.0,         // ② 玩家↔敌人：**只用来报警异常**。
                             //    被敌人顶在墙角时重叠最大——实测极端场景峰值 8.54
                             //    （敌人半径 15，相当于整个人压在身上），
                             //    而正常对撞只有约 1.2。取 15 才不会把正常挤压误报成缺陷。
                             //    想精细观察请看 maxCrush（峰值），不要看计数。
    GHOST_MIN_INTENT: 1.0,   // ③ 幽灵碰撞：本帧"想走"超过这个距离才算数
    GHOST_MAX_MOVED: 0.1,    //    实际几乎没动（<= 这个值）
    GHOST_PATIENCE: 3,       //    连续这么多帧才算"卡住"（避免单帧抖动误报）
    /* ④ 幽灵碰撞的**例外**：与敌人贴到这么近（逻辑像素）就算"移动被敌人吃掉了"，
     *    不算幽灵碰撞 —— 敌人挤玩家是正常物理，不是"位移被静默丢弃"。
     *    详见 tick() 里那段说明。 */
    GHOST_ENEMY_TOL: 2.0,
    lastDeep: 0,
    lastPair: '',
    maxSpeed: 0,
    maxCrush: 0,             // 玩家↔敌人的**峰值**重叠（比计数更能说明问题）
    ghostStreak: 0,          // 连续"想动却没动"的帧数
    ghostMaxStreak: 0,
    prevX: 0, prevY: 0, prevOk: false,

    reset: function () {
        COLCHECK.log = [];
        COLCHECK.counts = { cross: 0, tunnel: 0, crush: 0, ghost: 0, checks: 0 };
        COLCHECK.lastDeep = 0;
        COLCHECK.lastPair = '';
        COLCHECK.maxSpeed = 0;
        COLCHECK.maxCrush = 0;
        COLCHECK.ghostStreak = 0;
        COLCHECK.ghostMaxStreak = 0;
        COLCHECK.prevOk = false;
    },

    /* 是否处在"该检查"的状态 */
    armed: function () {
        return Game.mode === 'play' && Game.player && layer === GAME_LAYER;
    },

    tick: function () {
        if (!COLCHECK.armed()) return;
        var P = Game.player, i;
        var obs = obstacles();
        COLCHECK.counts.checks++;

        /* 记录最高速度（判断隧穿风险用） */
        var sp = Math.sqrt(P.vx * P.vx + P.vy * P.vy);
        if (sp > COLCHECK.maxSpeed) COLCHECK.maxSpeed = sp;

        /* ① 穿墙：玩家仍与障碍深度重叠 */
        for (i = 0; i < obs.length; i++) {
            var h = aabbRectMTV(P, obs[i]);
            if (h && h.pen > COLCHECK.TOL_WALL) {
                COLCHECK.counts.tunnel++;
                COLCHECK.lastDeep = h.pen;
                COLCHECK.lastPair = '玩家 ↔ 障碍#' + i;
                if (COLCHECK.log.length < 200) COLCHECK.log.push('穿墙 玩家↔障碍#' + i + ' 深度 ' + h.pen.toFixed(2));
            }
        }

        /* ② 被挤压：玩家与敌人重叠过深 */
        for (i = 0; i < Game.enemies.length; i++) {
            var E = Game.enemies[i];
            var mm = aabbMTV(P, E);
            if (mm) {
                var pen = mm.pen;
                if (pen > COLCHECK.maxCrush) COLCHECK.maxCrush = pen;
                if (pen > COLCHECK.TOL_ENEMY) {
                    COLCHECK.counts.crush++;
                    COLCHECK.lastDeep = pen;
                    COLCHECK.lastPair = '玩家 ↔ 敌人#' + i;
                    if (COLCHECK.log.length < 200) COLCHECK.log.push('被挤压 玩家↔敌人#' + i + ' 深度 ' + pen.toFixed(2));
                }
            }
        }

        /* ③ 幽灵碰撞（假阳性）：**几何上完全没重叠，却动不了**。
         *
         * ⚠️ 这是之前哨兵的**盲区**，由用户试玩发现：
         *    原来的指标只看"最终有没有重叠"与"分离函数会不会误报"，
         *    而这类问题的特征是——**位置合法，但每帧位移被吃掉**。
         *    外部工具测了 62 万组"碰撞函数"组合都查不出来，
         *    因为碰撞函数本身没错，错在**调用它的方式**。
         *
         * 判据（三条同时成立才算）：
         *   · 本帧"想走"的距离 > GHOST_MIN_INTENT
         *   · 实际几乎没动（<= GHOST_MAX_MOVED）
         *   · 此刻与任何障碍都**没有**重叠（有重叠就是正常的撞墙）
         * 并且要求**连续** GHOST_PATIENCE 帧，避免单帧数值抖动误报。 */
        var intent = Math.sqrt(P.vx * P.vx + P.vy * P.vy);
        if (COLCHECK.prevOk) {
            var moved = Math.sqrt((P.x - COLCHECK.prevX) * (P.x - COLCHECK.prevX) +
                                  (P.y - COLCHECK.prevY) * (P.y - COLCHECK.prevY));
            var clear = worstPenetration(P, obs) <= 0.02;
            /* ⚠️ 关键补充：**"顶住墙不动"和"幽灵碰撞"在几何上无法区分**
             *    （都是"没重叠 + 动不了"）。必须再补一条——
             *    按本帧**想走的位移**试探推进一次：若推进后**确实会撞上**，
             *    那是正常被墙挡住；**不会撞却动不了**，才是幽灵碰撞。
             *    （实测踩过：少了这一条，正常顶着墙走会被误报成一堆幽灵碰撞。） */
            var blk = { x: P.x + (P.intentDx || 0), y: P.y + (P.intentDy || 0), half: P.half };
            var blocked = worstPenetration(blk, obs) > 0.02;
            /* ⚠️⚠️ 还必须排除**被敌人顶住**（实测踩过，会让"幽灵碰撞"误报）：
             *    被敌人贴着推时，玩家"想走却没动 + 几何上没和墙重叠"三条全中，
             *    但那不是幽灵碰撞 —— 位移是被敌人实体吃掉的，物理上完全正常。
             *    实测：`test-spawn` ⑧（玩家一直按 S，敌人从四面围上来）300 帧里
             *    有约 4% 的概率记到 1 次 ghost，全部是这种情况。
             *    判据：与任何敌人**相邻/重叠**（留 GHOST_ENEMY_TOL 容差）就算"有解释"。 */
            if (!blocked) {
                for (var q = 0; q < Game.enemies.length; q++) {
                    var nq = Game.enemies[q];
                    if (Math.abs(P.x - nq.x) < P.half + nq.half + COLCHECK.GHOST_ENEMY_TOL &&
                        Math.abs(P.y - nq.y) < P.half + nq.half + COLCHECK.GHOST_ENEMY_TOL) { blocked = true; break; }
                }
            }
            if (intent > COLCHECK.GHOST_MIN_INTENT && moved <= COLCHECK.GHOST_MAX_MOVED && clear && !blocked) {
                COLCHECK.ghostStreak++;
                if (COLCHECK.ghostStreak > COLCHECK.ghostMaxStreak) COLCHECK.ghostMaxStreak = COLCHECK.ghostStreak;
                if (COLCHECK.ghostStreak === COLCHECK.GHOST_PATIENCE) {
                    COLCHECK.counts.ghost++;
                    COLCHECK.lastPair = '玩家 想走' + intent.toFixed(1) + ' 却停在 (' +
                        P.x.toFixed(1) + ',' + P.y.toFixed(1) + ')';
                    if (COLCHECK.log.length < 200) {
                        COLCHECK.log.push('幽灵碰撞 玩家停在 (' + P.x.toFixed(1) + ',' + P.y.toFixed(1) +
                            ') 想走 ' + intent.toFixed(1) + ' 实际 ' + moved.toFixed(3) + ' 且无重叠');
                    }
                }
            } else {
                COLCHECK.ghostStreak = 0;
            }
        }
        COLCHECK.prevX = P.x;
        COLCHECK.prevY = P.y;
        COLCHECK.prevOk = true;

        /* ④ 假阳性：抽一对"几何上分离"的物体，断言碰撞函数不会误报。
         *    用确定性取样（按帧号轮转），保证可复现。 */
        if (obs.length) {
            var idx = Game.frames % obs.length;
            var o = obs[idx];
            var probe = { x: o.x - P.half - 1, y: o.y - P.half - 1, half: P.half };   // 左上外侧 1px
            if (aabbRectMTV(probe, o)) {
                COLCHECK.counts.cross++;
                if (COLCHECK.log.length < 200) COLCHECK.log.push('假阳性 障碍#' + idx + '（未接触却判定碰撞）');
            }
        }
    },

    /* 给"圆↔圆"做一次独立性检查：碰撞函数返回 true 时，几何上必须真的相交 */
    verifyPair: function (a, b) {
        var dx = b.x - a.x, dy = b.y - a.y;
        var overlap = aabbOverlap(a, b);
        var reported = aabbMTV(a, b) !== null;
        if (overlap !== reported) COLCHECK.counts.cross++;
        return overlap === reported;
    }
};

