function hasPassive(n) { return Game.player && Game.player.passive.indexOf(n) >= 0; }
function levelNeed(lv) { return 5 * lv * (lv + 1); }

/* 按**等级**重算已解锁的技能数量。
 *
 * ⚠️ 依据原设计（`08` p12 / `09` 第 31 条）：技能**靠等级解锁**，不是花金币买。
 *    曾经的实现是"商店花 14 金买 + 同时卡等级"，还外加一段脚手架
 *    （`if (Save.level >= 2) Save.unlocked = 3;` 到 2 级白送全部）——
 *    那是 `08` 里已被废弃的技能点机制残留，两处都已删除。
 *
 * 规则：**只看带 `needLevel > 0` 的那些**，`needLevel <= Save.level` 即解锁。
 *
 * ⚠️⚠️ **它算的只是"按等级解锁的那几个"，不含 BOSS 解锁的**（`0.2.0` 起）。
 *    激光改成了"打赢第 4 关解锁"（`ACTIVES[3].boss`，见 `skillUnlocked`）——
 *    它的 `needLevel` 是 **0**，所以这里的 `> 0` 判断会把它跳过。
 *    ⚠️ **不要**把 `boss` 技能也算进这个计数：那样"练到 5 级"就会白送激光，
 *      而它本该是 BOSS 奖励。判"某个技能解锁没有"一律用 `skillUnlocked(i)`。 */
function recalcUnlocked() {
    var n = 0;
    for (var i = 0; i < ACTIVES.length; i++) {
        if (ACTIVES[i].needLevel > 0 && ACTIVES[i].needLevel <= Save.level) n++;
    }
    Save.unlocked = n;
    return n;
}

/* ⭐⭐ **某个技能解锁了没有**（`0.2.0` 加，用户改的解锁方式）。
 *
 * 用户原话：**"如果现在是 2/3/4 级解锁主动技 2/3/4，那改成 3/5 级解锁 2/3，
 *    第 4 关 boss 解锁 4"**。
 * ⇒ 现在有**两种**解锁方式，必须在这里合流，否则每个调用点都要各判一次：
 *    · `needLevel > 0` ⇒ 按等级（1 / 3 / 5 级）
 *    · `boss: true`    ⇒ **通关它自己 `bossLevel` 指的那一关**
 *      （激光 → 关卡 4；冻结 → 关卡 8，`0.2.1` 加）
 * ⚠️⚠️ **判"解锁"一律用这个函数**，不要再写 `i < Save.unlocked` ——
 *    那个计数**不含 BOSS 解锁的技能**（见 `recalcUnlocked` 的说明），
 *    用它判激光永远是"没解锁"。
 * ⚠️ `Save.unlockedExtra` 是真的存档数据（通关时写），不是派生值 ——
 *    但也**兼容"只看了 `cleared` 但没写 extra"的老存档/测试"**：
 *    两条路任一成立就算解锁。 */
function skillUnlocked(i) {
    var a = ACTIVES[i];
    if (!a) return false;
    if (a.boss) {
        /* ⚠️ `Save.cleared` 可能不是数组（极老的存档）⇒ 先兜一下再读。
         * ⭐⭐ **看这一条技能自己的 `bossLevel`**（`0.2.1` 改）：
         *    原来读全局常量 `BOSS_SKILL_LEVEL`（只有关卡 4 一个值）——
         *    加了第 5 个主动「冻结」（首通**关卡 8**）之后，一个常量表达不了两个关卡
         *    ⇒ 判据挪到每条技能自己身上（"哪关解锁哪个技能"本来就该跟着技能走）。 */
        return (Array.isArray(Save.unlockedExtra) && Save.unlockedExtra.indexOf(i) >= 0) ||
               !!(Array.isArray(Save.cleared) && Save.cleared[a.bossLevel]);
    }
    return a.needLevel > 0 && a.needLevel <= Save.level;
}

/* ⭐ **道具是否已拥有**（`0.2.0`，用户定：第 2 个道具在商店 30 金永久解锁）。
 * ⚠️ 与被动同一套思路：`ITEMS[i].unlock === 0` 的**一开始就有**，
 *    其余要买（`Save.itemOwned`）。 */
function itemOwned(i) {
    if (!ITEMS[i]) return false;
    if (ITEMS[i].unlock === 0) return true;
    return Array.isArray(Save.itemOwned) && Save.itemOwned.indexOf(i) >= 0;
}

/* 下一个还没解锁的技能还要几级（全解锁时返回 0），给界面显示用。
 * ⚠️ BOSS 解锁的技能（`needLevel: 0`）**不参与**"还要几级" ——
 *    它不是练出来的，报个等级反而误导（界面另有文案说"通关第 4 关"）。 */
function nextUnlockLevel() {
    for (var i = 0; i < ACTIVES.length; i++) {
        if (ACTIVES[i].needLevel > 0 && ACTIVES[i].needLevel > Save.level) return ACTIVES[i].needLevel;
    }
    return 0;
}

/* ⭐ 被动是否已解锁 = **是否在商店买过**（`Save.purchasedPassives`）。
 * ⚠️ 和技能是**两套**机制，别混：
 *    · 主动 → `recalcUnlocked()` 按 `Save.level` 算出来（派生值，不花钱）
 *    · 被动 → 玩家在商店花金币买的（真数据，存在档案里）
 * ⚠️ 用**下标查数组**而不是另存一份布尔，这样只有一个真相来源；
 *    `indexOf` 对 6 个元素的数组完全够快，而且每次读都是最新的。 */
function passiveUnlocked(i) {
    return Save.purchasedPassives.indexOf(i) >= 0;
}

/* 买一个被动：够钱才成功。⚠️ 扣钱 + 记档 + 存盘都在这儿，
 * 调用方（商店按钮）只负责重建界面 —— 免得扣钱逻辑散在 UI 里。 */
function buyPassive(i) {
    if (i < 0 || i >= PASSIVES.length) return false;
    if (passiveUnlocked(i)) return false;
    if (Save.gold < PASSIVES[i].price) return false;
    Save.gold -= PASSIVES[i].price;
    Save.purchasedPassives.push(i);
    saveNow();
    return true;
}

