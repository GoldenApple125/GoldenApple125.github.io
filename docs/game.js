        /* ⚠️ 法力初始值在 startLevel 里会**补满**（见那里的说明）。
         *    这里写 mpMax 而不是 BAL.player.mp，避免"默认值看起来像没满"。 */
        mpMax: playerMpMax(), mp: playerMpMax(),
        mpRegen: b.mpRegen + lvUp * b.perLevel.mpRegen,
