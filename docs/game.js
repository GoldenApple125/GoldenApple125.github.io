function addExp(n) {
    Save.exp += n;
    var ups = 0;
    /* ⚠️ **这里没有等级上限**（用户 2026-10-01 定）：等级可以一直升，
     *    经验也照常累积 —— 只有**属性加成**在 `ATTR_MAX_LEVEL` 封顶（见 `levelSteps`）。
     *    所以不要在这里写 `if (Save.level >= 某值) return` 之类的封顶逻辑。 */
    while (Save.exp >= levelNeed(Save.level)) {
        Save.exp -= levelNeed(Save.level);
        Save.level++;
        ups++;
    }
    /* ⚠️ 升级后**必须**重算解锁（升级是解锁的唯一来源）。
     *    也要在"设置了等级但没走 addExp"的路径上调用 —— 所以各入口都调一次。 */
    if (ups > 0) recalcUnlocked();
    return ups;
}

