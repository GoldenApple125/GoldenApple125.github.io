/* 一条光束这一帧是否打到玩家。
 *
 * ⚠️⚠️ **光束是"半直线"**（从源头沿 `ang` 一直射出去），不是线段：
 *    · `t < 0` = 玩家在**源头背后** ⇒ 不打（少了这一条，"光束背后"也会被打到）
 *    · 距离用 **AABB 在法向上的投影半径** `half × (|nx| + |ny|)` ——
 *      这是轴对齐矩形**精确**的支持函数（不是拿半径 14 当圆去近似，
 *      那样四角会差最多 5.8px，正是本项目反复强调的那件事）。
 * ⚠️ 判定宽度 = `BOSS2.beamHalfFire`（生效期的半宽）**不是**警示期的细线宽度。 */
function beamHitsPlayer(b, P) {
    var ux = Math.cos(b.ang), uy = Math.sin(b.ang);
    var t = (P.x - b.x) * ux + (P.y - b.y) * uy;      /* 沿光束方向的投影 */
    if (t < 0) return false;
    /* ⭐⭐ **不穿墙的光束**（`0.3.1` 小怪 6 ✗）：投影超过它自己的 `len` ⇒ 打不到 ✔
     *    （`b.len` 在召唤时量好 ✗；BOSS2 没有这个字段 ⇒ 无上限 ⇒ 照旧穿墙 ✔）。 */
    if (typeof b.len === 'number' && t > b.len) return false;
    var nx = -uy, ny = ux;                            /* 光束轴线的法向 */
    var d = (P.x - b.x) * nx + (P.y - b.y) * ny;      /* 玩家中心到轴线 */
    var r = P.half * (Math.abs(nx) + Math.abs(ny)) + BOSS2.beamHalfFire;
    return Math.abs(d) <= r;
}

/* ⭐ **光束打到"地图底部"那一点的横坐标**（`0.2.1`）——
 *    `render.js`（画那块的标记）与 `updateBeams`（在同一个点生火花）**共用它**。
 *
 * ⚠️⚠️ **必须只有这一份算法**：底部标记（画）与底部火花（生）是**同一个交点**，
 *    各写一遍必然漂移（"看着在这里、火花在那里"）；而且光束是**斜的**，
 *    交点 ≠ `b.x`（`b.x` 是**上边界**上的起点）。
 * ⚠️ 推导：从 `(b.x, b.y)` 沿 `(cos a, sin a)` 走到 `y = LOGICAL_H`
 *    ⇒ 参数 `t = (LOGICAL_H - b.y) / sin(a)`，横坐标 `= b.x + cos(a) · t`。
 *    `b.y` 恒为 0、`sin(a) = cos(倾角) ≈ 1`（光束近似竖直）⇒ 分母不会接近 0。 */
/* ⭐⭐ **光束的"出屏点"**（`0.3.1` 修 ✗）：沿**光束自己的方向**从 `(b.x, b.y)` 走，
 *    取它**离开屏幕**的那一点 ✔ —— 用来放"远端主闪 + 碎屑"与渲染那块标记 ✔。
 *
 * ⚠️⚠️ 原来是 `beamBottomX(b)` ✗ —— 它**只算"打到屏幕【下边】"的交点** ✔：
 *    对 BOSS2 没问题（它只朝下打 ✗），但小怪 6 会**朝上**打 ⇒ 火花被放到屏幕另一头 ✔
 *    （用户实测："怪物瞄准在上半屏时，命中效果的主闪/火花位置沿激光方向相反" ✔）。
 * ⚠️ 现在按 `ang` 的符号分别与四条边求交 ✗，取**最小正 t** ✔（射线与矩形求交的标准做法 ✔）。
 * ⚠️ 竖直/水平光束的除零风险：用 `1e-6` 判"该方向有没有分量" ✗ ✔。 */
/* ⭐ **光束"打到哪"的那个点**（`0.3.1` ✗）：有 `len`（不穿墙 ✗）就沿方向走 `len`，
 *  否则退回屏幕边界（原 `beamFarPoint` ✗ = BOSS2 的穿墙光束 ✔）。 */
function beamFarEnd(b) {
    if (typeof b.len === 'number') {
        return { x: b.x + Math.cos(b.ang) * b.len, y: b.y + Math.sin(b.ang) * b.len };
    }
    return beamFarPoint(b);
}

function beamFarPoint(b) {
    var ux = Math.cos(b.ang), uy = Math.sin(b.ang);
    var t = Infinity;
    if (ux > 1e-6) t = Math.min(t, (LOGICAL_W - b.x) / ux);
    else if (ux < -1e-6) t = Math.min(t, (0 - b.x) / ux);
    if (uy > 1e-6) t = Math.min(t, (LOGICAL_H - b.y) / uy);
    else if (uy < -1e-6) t = Math.min(t, (0 - b.y) / uy);
    if (!isFinite(t) || t < 0) t = 0;
    return { x: b.x + ux * t, y: b.y + uy * t };
}

/* 光束的每帧推进（`update()` 里调一次）。
 *
 * 阶段（用户定）：**警示 20~30 帧（红细线，不判定）→ 生效 20 帧（每帧判定、伤害 3）**。
 *    ⚠️ 警示帧数读 `BOSS2.beamWarn`（用户调过几轮），别在这里写死。
 * ⚠️ `warn` 与 `fire` 都归零后**从数组里移除** —— 不然会一直留在 `Game.beams` 里
 *    （画面上看不见，但每帧还在跑判定）。
 * ⚠️ 伤害交给 `hurtPlayer(3)`（它自己管无敌帧）——
 *    用户原话："伤害3/帧（由于主角有无敌其实只会吃一帧）"。 */
function updateBeams(P) {
    for (var i = Game.beams.length - 1; i >= 0; i--) {
        var b = Game.beams[i];
        /* ⭐⭐ **激光源在"召唤出来"时就定死** ✗（用户 2026-10-05："要和玩家类似，召唤的是激光源，
         *    也就是召唤出来后激光位置固定，不随怪物移动" ✔）。
         *  ⚠️ 早先那版让原点**跟着本体走** ✗ ⇒ 已删除 ✔；`b.x / b.y` 从此不再被更新 ✔。
         *  ⚠️ 角度本来就在警示开始时定死 ✗（`b.ang` ✗）⇒ 现在**位置与角度都是固定的** ✔。 */
        if (b.warn > 0) { b.warn--; continue; }        /* 警示期：只画线、不判定 */
        if (b.fire > 0) {
            /* ⭐⭐ **地图底部那个命中点也要冒火花**（`0.2.1` 用户："**命中底部缺少对应火花**"）。
             * ⚠️ 只冒**一次**（`b.sparked` 标记）—— 与玩家激光"命中点动画"同一条规矩：
             *    那是**首次接触**的那一下，不是每帧持续喷（持续喷会糊成一片、还白烧粒子）。
             * ⚠️ 位置用 `beamBottomX(b)`：与 `render.js` 画的那块标记**同一个点**。 */
            if (!b.sparked) {
                b.sparked = true;
                /* ⚠️⚠️ **`'under', true` 不能省**（`0.2.1` 修）：
                 *    玩家激光的命中火花是"**碎屑在 `#fx`（光束之下）、主闪在 `#fx2`（光束之上）**"
                 *    （用户当时的要求："激光主闪和火花都改成高于激光，主闪高于火花"）。
                 *    ⚠️ 我第一版**漏传了这两个参数** ⇒ 整簇（含主闪）都落在 `#fx`
                 *      ⇒ **主闪被光束压住**，与"和玩家激光对应"不符；
                 *      而代码注释里却写着"与打中敌人时完全一致" ⇒ **注释在说谎**。
                 *    ⇒ 现在两处生成点都显式传 `'under', true`，并有断言钉住层级。 */
                var fp = beamFarEnd(b);   /* ⚠️ 不穿墙的光束 ⇒ 火花落在**墙边** ✗（原来只算屏幕边 ✔） */
                laserSparks(fp.x, fp.y, PAL.beamFireCore,
                            dimHex(PAL.beamFireCore, LASER_SPARK_DIM), 'under', true,
                            BOSS2.sparkFrames);
            }
            if (P.inv <= 0 && beamHitsPlayer(b, P)) {
                hurtPlayer(b.dmg || BOSS2.beamDmg);   /* ⭐ 每束自带伤害（小怪 6 = 2 ✗）✔ */
                /* ⭐⭐ **命中玩家的动画**（`0.2.1` 用户："命中玩家（与玩家激光对应，
                 *    但因为boss2激光穿墙所以不加入命中墙的动画）"）。
                 * ⚠️ **复用玩家激光那套火花**（`laserSparks`）—— 这就是"与玩家激光对应"：
                 *    同一套观感（1 颗主闪 + N 颗碎屑、碎屑是同色压暗），
                 *    颜色换成光束的亮粉红（`BEAM_FIRE_CORE`）。
                 * ⚠️ `layer='under'` + `mainOver=true` 与玩家激光**打中敌人**时**完全一致**：
                 *    碎屑在 `#fx`（光束之下）、主闪在 `#fx2`（光束之上）。
                 *    ⚠️ **这两个参数必须显式传** —— 第一版漏了（见上面底部火花那段说明），
                 *      结果主闪被光束压住。
                 * ⚠️ 只在**真的造成伤害那一帧**生火花（`P.inv <= 0` 已经判过）——
                 *    否则无敌帧里会每帧刷一簇，糊成一片。
                 * ⚠️⚠️ **不生成"命中墙"的火花**：boss2 的激光**穿墙**（用户明确要求），
                 *    所以中途的墙不算命中点（两端只有"源"和"地图底部"两个标记）。 */
                laserSparks(P.x, P.y, PAL.beamOuter, dimHex(PAL.beamOuter, LASER_SPARK_DIM),
                            'under', true, BOSS2.sparkFrames);
            }
            b.fire--;
        }
        if (b.warn <= 0 && b.fire <= 0) Game.beams.splice(i, 1);
    }
}
/* 命中/爆炸特效：**从 `t=12` 开始渐缩**（尺寸 = `t × 2 × half / 12`），缩到 0 就消失。
 * 满尺寸正好是 `half × 2` 见方 —— 传谁的 `half` 就跟谁一样大。
 *
 * ⭐⭐ `half` 的取值规则（`0.2.0` 定稿，**每个"命中"调用点都按这条**）：
 *
 *     half = **命中物的 half + `BAL.player.hitGrowHalf`**（加法增量，不是比例）
 *
 *     · 普攻 10×10 → 24×24（+14）
 *     · 单发点射 20×20 → 34×34（+14）
 *     ⇒ **每种子弹"增大的量"一致**，大子弹不会因比例而胀得过大。
 *
 * ⚠️⚠️ 这里以前是**固定 24×24**，于是同一次"击中"、不同子弹看到的不是一回事
 *    （用户实测："那个大子弹打中后直接缩小，其他都是先变大后缩小"）：
 *      单发点射 20×20 → 24×24（只大 4px）⇒ 看着"直接缩小"
 *      普攻     10×10 → 24×24（大 14px） ⇒ 看着"先变大"
 *    ⚠️ 这个尺寸差**从 `0.1.1` 就存在**，不是 `0.2.0` 引入的。
 *    ⚠️ 中途我误改成"所有子弹都扩到同一个尺寸（敌人那么大）" —— **那是错的**：
 *      用户要的是"增大的量一样"，不是"增大到一样"。
 *
 * ⭐ **击杀**那朵是唯一例外：传 `t.half`（= 敌人 30×30 → 缩到 0）。
 *    它必须与敌人**完全重合**，否则敌人一消失就显得"敌人缩了一下"。
 *
 * ⚠️⚠️ 这里**曾经**还有过一个 `hold`（满尺寸定格的帧数），现在已经**删干净**了。
 *    它是为了"让击杀爆炸活到结算框弹出"加的 —— 而那个方向**从头到尾都是错的**：
 *      · 长 hold（= resultDelay）⇒ 每个敌人都僵 0.6 秒
 *      · 短 hold + 锁定 ⇒ 最后一个敌人僵 0.6 秒
 *      · 最后发现真凶是 `update()` 开头的提前 `return`（见那里的说明）
 *    ⇒ **特效永远按自己的生命周期走，结算延迟只延迟弹窗、不改变任何动画。**
 *    所以别再往这里加"定格 / 锁定 / 延寿"之类的参数了。 */
function pop(x, y, c, half) {
    Game.fx.push({ x: x, y: y, t: 12, half: half || 12, c: c || PAL.hitWhite });
}

/* ⭐⭐ **激光能打多远**（`0.2.0`）：从 (x,y) 沿 angle 走，撞到障碍就停，最长 `LASER.len`。
 *
 * ⚠️⚠️ **每一步要探"这一小段"，不是"从起点到这里的整条带子"**（这里错过一次）。
 *    第一版写的是 `var seg = laserAABB(x, y, angle, d, half)` 然后直接拿它的包围盒去判 ——
 *    而 `laserAABB(..., d, ...)` 返回的是**从起点一直延伸到 d 的整条带子的包围盒**，
 *    于是探针**随着 d 一起从玩家身上长出去**（实测 `d=700` 时它已经是
 *    `y[-348, 368]` 的一大块），只有整条盒子碰到墙才会命中。
 *    ⇒ 后果：**中间有掩体时会直接穿过去**，只在"整条线一直撞到边界"时才截断
 *      （实测：从 (640,360) 朝上明明 360px 就该撞到上边界，它却返回 707）。
 *    ⇒ 正确做法：**只取"这一步新长出来的那一小条"**。
 *      关键观察：`laserAABB(..., 0, ...)` 本身就是一个 `2half × 2half` 的小方块，
 *      而 `laserAABB(..., d, ...)` 相对它只多出**两条边**，增量是确定的
 *      （沿轴向 = `|dir| × d`，垂直向 = `|dir| × half`）
 *      ⇒ 直接按增量造那一小条，**不用做集合运算**。
 *    ⚠️⚠️ 这一小块修过两次，两次都错在"怎么表达那一小条"：
 *      第一次拿**整条带子**的包围盒去判（探针从玩家身上一路长出去）；
 *      第二次改用**交集**，而 `laserAABB(..., 0, ...)` 是 `cur` 的子集
 *      ⇒ 交集恒等于它、探针钉在玩家身上不动（实测 `d` 涨到 385 而探针一直是 `y[352,368]`）。
 *      **"整条 / 交集 / 差集"三种写法里只有差集对**，所以这里干脆按增量直接算。
 *
 * ⚠️ 返回的是**能打到的最远距离**（可能小于 `LASER.len`）。
 *    步长必须显著小于最薄的墙（`TILE = 40`），否则会跳过薄墙 ——
 *    现在约 8px，余量 5 倍。改 `LASER.len` 时余量会跟着变（步长 = len / maxSteps）。 */
/* ⭐⭐ **从 `(x, y)` 沿 `angle` 量到第一堵墙的距离**（玩家激光与小怪 6 的光束共用 ✗）。
 *  ⚠️ `0.3.1` **参数化** ✗：`maxLen` / `halfW` 可覆盖 —— 玩家用默认（`LASER.len` ✗ / `LASER.halfWidth` ✗），
 *     小怪 6 的光束传屏幕对角线 + `BOSS2.beamHalfFire` ✗ ⇒ **行为与各自原来完全一致** ✔。
 *  ⚠️ 做法是"**步进探针**" ✗（每步放一个带半宽的盒子去撞障碍 ✗）⇒ 偏保守（宁可早停 ✗）✔。 */
function laserReach(x, y, angle, maxLen, halfW) {
    var obs = obstacles();
    var LEN = (typeof maxLen === 'number' && maxLen > 0) ? maxLen : LASER.len;
    var HW = (typeof halfW === 'number' && halfW > 0) ? halfW : LASER.halfWidth;
    var step = LEN / LASER.maxSteps;
    var c = Math.cos(angle), s = Math.sin(angle);
    var hw = HW;
    /* 第 k 步新长出来的那一小条：沿着方向推进了 `step`，宽度仍是 `2hw` */
    var alongX = Math.abs(c) * step + Math.abs(s) * hw;
    var alongY = Math.abs(s) * step + Math.abs(c) * hw;
    var d, i, k;
    for (k = 1; k <= LASER.maxSteps; k++) {
        d = step * k;
        /* 这一小条的中心 ≈ 起点沿方向走 `d - step/2` 处 */
        var mx = x + c * (d - step / 2), my = y + s * (d - step / 2);
        var probe = { x: mx, y: my, half: Math.min(alongX, alongY) / 2 };
        /* ⚠️ 用两个方向里**较小的**那个当 half：宁可少判一点（不虚胖），
         *    代价是斜向时比实际带子略窄 —— 对"撞墙截断"来说偏保守是对的。 */
        for (i = 0; i < obs.length; i++) {
            if (aabbRectMTV(probe, obs[i])) return d - step;
        }
    }
    return LEN;
}

/* ⭐⭐⭐ **激光的命中点动画**（`0.2.0`）。
 *
 * 用户原话：**"我希望的是命中点产生动画，包括墙和敌人首次接触该道激光的地方"**。
 *
 * ## 它和 `pop`（子弹命中）的区别
 * `pop` 是"一次性"的：命中那一刻在**敌人身上**放一个 12 帧的方块，缩完消失。
 * 激光这样做**不行** —— 它是帧伤、每帧都命中：
 *   · 照抄 ⇒ 20 帧 × N 只敌人 ⇒ 几百个对象，而且方块叠在敌人身上糊成一坨
 *   · 观感也不对：用户要的是"**打在哪儿**"，不是"敌人整个在亮"
 * ⇒ 所以改成：**只在"命中点"冒一次火花**（小方块向外飞散、缩小消失），
 *   而且**墙也算**（光束撞墙那个点同样冒）—— 这正是"命中点"的字面意思。
 *
 * ## 数据
 * `Game.sparks` —— 火花粒子，一次性、自己飞散消失。
 * `Game.laserContact` —— **上一帧已经在冒火花的联系人**（按深度 d 索引）：
 *   敌人用对象引用当 key，墙用字符串 `'w'`（一道光束最多撞一面墙）。
 *   ⚠️ 用它来保证"**首次接触**才冒"（用户明确说的"首次接触"）：
 *      同一个 `d` 上一帧已经在冒 ⇒ 跳过；`d` 变了（比如换了一只敌人）⇒ 当作新接触。
 * ⚠️ 每帧清的 `laserContact` 是**相对一道光束**的：`castSkill` 里重置。 */
var SPARK_FRAMES = 24;             /* 火花寿命（帧） */
var SPARK_PER_HIT = 6;             /* 一个命中点点几颗（一次性的，不是每帧） */

/* ⭐⭐ **激光命中特效的配色**（`0.2.0`，用户要求）。
 *
 * 用户原话：**"让激光打中敌人的主闪和火花用其他颜色（就像子弹打中敌人是黄色动画，
 * 主闪也用这个颜色，火花对应更暗的颜色）"**。
 *
 * ⚠️⚠️ **为什么用 `P_COLOR` 而不是"敌人的颜色"**：子弹打中敌人用的就是 `P_COLOR`
 *    （见子弹命中那行的 `pop(b.x, b.y, P_COLOR, …)`）—— 那是"**我方伤害**"的统一色。
 *    激光也是我方伤害 ⇒ 跟着它走，玩家一眼就知道"这是我在打它"。
 *    ⚠️ 第一版用的是**敌人自己的颜色**（`lt.color`，红/紫），和"被打中"这件事不搭。
 *
 * ⚠️ 碎屑的暗黄 = `dimHex(主闪色, LASER_SPARK_DIM)` ⇒ **同色相、只压暗**，
 *    比"换个颜色"更像"同一个东西的碎屑"。
 * ⚠️ `0.5` 是按实测定的：`#f8d80d`（亮度 202）⇒ `#7c6c07`（亮度 **101**，
 *    正好一半），而游戏背景 `#14161a` 亮度只有 **22** ⇒ 暗黄仍然清楚可见。
 *    再暗（0.3 以下）就贴近背景、等于看不见了。 */
var LASER_SPARK_HIT  = PAL.hitPEnemy;                 /* 打中敌人：用“打到对方”那一档（= 子弹的暗色，用户 2026-10-02 定） */
var LASER_SPARK_WALL = PAL.hitPWall;               /* 打中墙：用“打到墙”那一档（= 子弹的亮色；与打中敌人区分开） */
var LASER_SPARK_DIM  = 0.5;                     /* 碎屑 = 主闪压暗到这个系数 */

/* ⚠️⚠️ **尺寸按"光束宽度"定标，不要凭感觉给小数**（用户实测反馈："火花我看到了，太小了"）。
 *    第一版给的是 `s = 2 + random*2`（2~4px）—— 而**光束本身就有 16px 宽**，
 *    2px 的火花在一条 16px 的光带旁边等于看不见。
 *    ⇒ 现在：
 *      · **主闪**（第 0 颗）起始 `halfWidth × 4`（32px，`0.2.0` 又改成与普攻特效同尺寸）
 *      · **碎屑**（其余）起始 `halfWidth × 1~2`（8~16px）
 *    ⚠️ 两者的**衰减规律不同**：主闪缩得快（一闪就没）、碎屑缩得慢（飞出去才消失）
 *      ⇒ 所以每颗自带 `s0`（起始尺寸）与 `grow`（尺寸曲线指数）。
 *
 * `flash` = 主闪色、`frag` = 碎屑色。**调用方决定配色**（敌人 / 墙两套，见上面三个常量）。
 *
 * ⚠️ `layer` = **碎屑画到哪一层**（`0.2.0`，见 fxdom.js 的层级表）：
 *      · `'over'`  ⇒ `#fx2`（**光束之上**）
 *      · 省略      ⇒ `#fx` （**光束之下、玩家之上**）
 *    ⇒ 默认（含**药品**火花）就是"**高于玩家**"那一层 —— 用户要求
 *      "喝药火花层级应高于玩家"。
 *      ⚠️ 药品整组（主闪 + 碎屑）**都在 `#fx`**：它跟激光无关，
 *        跑到光束之上会莫名其妙压住激光。
 *
 * ⚠️ `mainOver` = **主闪要不要再高一档**（`#fx2`，光束之上）。
 *    · 激光命中传 `true` —— 用户要求 **"激光主闪和火花都改成高于激光，主闪高于火花"**：
 *      碎屑在 `#fx`（光束之下）、主闪在 `#fx2`（光束之上）⇒ 三条同时成立。
 *    · 药品不传 ⇒ 主闪与碎屑同层。
 *    ⚠️⚠️ **为什么不让函数自己"高一档"**：我们只有两层特效布，
 *      "比 `#fx` 高一档"只能是 `#fx2` —— 但那对药品是**错的**
 *      （它会压在激光光束上）。⇒ 这件事**没有默认答案**，必须由调用方表态。
 *      我试过"自动高一档"，测试当场抓到药品跑错层。
 *    ⚠️ 真要给"碎屑也在 `#fx2`、主闪还要更高"这种组合，**得再加一层布** ——
 *      现在做不到，别硬凑。
 *
 * ⚠️ `frames` = **寿命（帧）**，省略则用 `SPARK_FRAMES`（24）。
 *    · 玩家激光（敌人 / 墙 / 药品）都**不传** ⇒ 24 帧。
 *    · **BOSS2 的光束传 `BOSS2.sparkFrames`（34）** —— 用户要求"主闪和火花整体动画时长
 *      延长10帧，以匹配激光时间"（那一招的激光本来就比玩家的长 10 帧）。
 *    ⚠️ 尺寸曲线 `(t/max)^grow` 用的是**传入的 max** ⇒ 拉长寿命只是把动画放慢，
 *      形状不变（主闪依旧是"一闪就没"、碎屑依旧是"慢慢缩"）。 */
function laserSparks(x, y, flash, frag, layer, mainOver, frames) {
    var i, hw = LASER.halfWidth, life = frames > 0 ? frames : SPARK_FRAMES;
    var fragLayer = (layer === 'over') ? 'over' : 'under';
    var mainLayer = mainOver ? 'over' : fragLayer;
    for (i = 0; i < SPARK_PER_HIT; i++) {
        var main = (i === 0);
        var a = Math.random() * Math.PI * 2;
        var sp = main ? 0 : (0.8 + Math.random() * 1.6);
        Game.sparks.push({
            x: x, y: y,
            vx: Math.cos(a) * sp, vy: Math.sin(a) * sp,
            t: life, max: life,
            c: main ? flash : frag,               /* 主闪一颗、碎屑若干，颜色分开传 */
            layer: main ? mainLayer : fragLayer,
            /* ⭐⭐ **主闪的最大尺寸 = 普攻命中特效的最大尺寸**（`0.2.0`，用户明确要求
             *    "激光主闪最大值改成和普攻特效的最大值一致"）。
             *    ⚠️ 普攻那边是 `pop(x, y, 色, 子弹 half + hitGrowHalf)` ⇒ 最大边长
             *      `(bulletHalf + hitGrowHalf) × 2` = **(5 + 7) × 2 = 24**。
             *    ⚠️⚠️ **不要写死 24、也不要写成 `hw * 3`** —— 后者只是"碰巧等于 24"
             *      （`8 × 3`），一旦改 `halfWidth` 或 `bulletHalf` 就会**静默脱钩**。
             *      ⇒ 直接用那两个常量算出来（单一来源，改哪边都跟着走）。 */
            s0: main ? (BAL.player.bulletHalf + BAL.player.hitGrowHalf) * 2
                     : hw * (1 + Math.random() * 1),
            grow: main ? 2.2 : 0.75               /* 主闪一闪就没；碎屑慢慢缩 */
        });
    }
}

/* 判断"这个**东西**上一帧是不是已经在冒火花了"。返回 true = **首次接触**（该冒火花）。
 * ⚠️ `key` = **身份**：敌人用**对象引用**（自动转成字符串当键）、墙用字符串 `'wall'`。
 *
 * ⚠️⚠️ **绝不能用"深度/坐标"当 key**（用户实测报过：**打怪出多次、打墙只出一次**，
 *    并要求"**改成都是 1 次**"）。
 *    第一版用的是 `Math.round(alongE)`（敌人中心沿光束的投影距离）——
 *    看着"很合理"，但**敌人一直在动** ⇒ 深度每帧都在变 ⇒ **每帧都判成首次接触**
 *    ⇒ 同一只敌人身上每帧冒一簇火花（实测：敌人沿光束后退时深度 85→88→91…，
 *      10 帧新增 **60 颗**）。
 *    ⚠️ 而墙是**静止**的 ⇒ 深度不变 ⇒ 只冒一次 —— 于是现象就成了"墙 1 次、怪多次"，
 *      正是用户报的那个。
 *    ⇒ 改成身份当 key：**同一只敌人整段激光只冒一簇**，
 *      哪怕它一路被打得往后退（深度 85 → 112 也只冒一次）。
 *
 * ⚠️⚠️ **两张表轮换，不是"每帧清空"**（这也踩过一次）：
 *    在激光段开头写 `Game.laserContact = {}` 的话，
 *    **永远没有"上一帧"可比** ⇒ 每帧都判成首次（实测火花总数 10→20→30→40 一路涨）。
 *    ⇒ 正确做法：`laserContact` = **这一帧**、`laserContactPrev` = **上一帧**；
 *      激光段开头 **swap** 两张表，再把新的那张清空。 */
function laserContactNew(key) {
    Game.laserContact[key] = 1;                   /* 登记到**这一帧**的表里 */
    return !Game.laserContactPrev[key];
}

/* ⭐⭐ **击杀一只敌人的全部后果**（`0.2.0` 从子弹循环里抽出来的）。
 *
 * ⚠️⚠️ **为什么要抽**：这套级联（计数 + 经验 + 金币 + 死亡特效）原来**内联在
 *    玩家子弹的命中分支里**。加激光时如果照抄一遍，就成了**两处必须同步**的代码 ——
 *    以后改奖励规则（比如"BOSS 首通额外奖励"）只改一处，另一处静默不同步，
 *    而"少给奖励"这种 bug 不会报错，只会被玩家发现。
 *    ⇒ 现在**只有这一处**。任何新的伤害来源都应该调它，不要自己抄一遍。
 *
 * ⚠️ 它**只负责"死掉的后果"**，不负责从 `Game.enemies` 里删除 ——
 *    因为不同调用方的遍历方式不同（子弹是倒序 splice、激光是先收集再删）。
 *    调用方自己把这只从数组里移掉。 */
/* ⭐ **还剩下几只"必须清掉"的敌人**（`0.3.1` ✗）：**跳过召唤物** ✔。
 *  ⚠️ 通关判定原来是 `Game.enemies.length === 0` ✗ ⇒ BOSS3 召出来的那两只**会挡住通关** ✔
 *     （用户明确要求"不影响通关判定" ✗）⇒ 改成数"非召唤物" ✔。
 *  ⚠️ 不用 `filter`（每帧都会跑 ✗）：手写循环、不分配数组 ✔。 */
function requiredLeft() {
    var n = 0, i;
    for (i = 0; i < Game.enemies.length; i++) if (!Game.enemies[i].summoned) n++;
    return n;
}

function killEnemy(t) {
    /* ⚠️⚠️ **召唤物不给奖励、也不计入杀怪** ✗（用户："打败召唤的怪不给奖励，不计入杀怪，
     *    不影响「进度」和通关判定" ✔）⇒ BOSS3 召出来的那两只在这里就返回 ✔。
     *    ⚠️ 死亡特效（`pop` ✗）**照旧要给** ✔ —— 不然打死它毫无反馈 ✔。 */
    if (t.summoned) { pop(t.x, t.y, t.color, t.half); return; }
    Game.kills++;
    /* ⭐ **本波**的击败数（`0.2.1` 波次）。与 `kills` 分开累加：
     *   · `kills`      = 整关累计 ⇒ 给结算用
     *   · `waveKills`  = 本波累计 ⇒ 给 HUD 的"波次 x/y 进度 a/b"用（用户要求分母是本波的）
     * ⚠️ 单波关卡里两者的值**恰好相等**（`waveKills` 在 `startLevel` 里归零，之后同步涨），
     *    所以多波那行代码不会影响任何单波行为。 */
    Game.waveKills++;
    /* ⭐ **奖励按种类累计**（`0.2.0`）：每只怪值多少写在 `ENEMY_TYPES` 那一行
     *    （`exp`/`gold`），这里只做累加 —— `endLevel` 直接用累计值。
     * ⚠️ 兜底到 `BAL.kill`：万一某个种类忘了写，也不该算成 0 奖励
     *    （少给奖励比"报错"更难被发现，与 `LEVELS[].clear` 同一套理由）。 */
    Game.killExp += (typeof t.exp === 'number') ? t.exp : BAL.kill.exp;
    Game.killGold += (typeof t.gold === 'number') ? t.gold : BAL.kill.gold;
    /* ⭐ 击杀特效 = **和敌人一样大**，然后**立刻**开始渐缩。
     *    · 一样大（`t.half`）⇒ 观感是"敌人本身碎掉"，
     *      而不是"敌人内部冒出个小方块"（那会显得敌人缩了一下）
     * ⚠️ **定格 = 0**（与 `0.1.1` 一致）。曾经加过 4 帧顿挫，
     *    用户实测觉得"比 0.1.1 慢了"⇒ 已改回。
     *    0.1.1 就是 `pop(t.x, t.y, E_COLOR)` —— 12 帧、无定格。
     * ⚠️ 不管它是不是"最后一个敌人"，**都用同一个特效** ——
     *    结算延迟不去"留住"它（前三次就是在这里反复加戏，
     *    详 `pop` 与 `update()` 特效段的说明）。
     * ⭐ 颜色用**这只敌人自己的** `t.color`（两种小怪不同色 ⇒ 爆炸也跟着是它自己的颜色）。 */
    pop(t.x, t.y, t.color, t.half);
}

function fireAuto(P) {
    /* 基准方向 = 瞄准方向。⚠️ 这一行算出来的 `a` **必须**加到每一发的相对角上 ——
     *    第一版就是算了 `a` 却没用它，直接把相对角（0 / ±5°）当成绝对角发出去 ⇒
     *    **不管准星朝哪，子弹都朝 +X（正右）飞**（实测：朝正上打，弹却往右跑）。
     *    ⇒ `fireAutoAngles()` 返回的是**相对瞄准方向的偏移**，不是绝对角。 */
    var a = Math.atan2(Input.aimY, Input.aimX);
    /* ⭐⭐ **一次开火可能射出多发**（`0.2.0`，被动 4 / 5）。
     *    偏移量全部由 `fireAutoAngles()` 决定（它负责"几颗、各自偏多少"），
     *    这里负责"加上基准方向、把每一颗从身体边缘发出去"。
     * ⚠️ 伤害仍走 `playerAutoDmg()`，**不要在这里写死数字** ——
     *    以前就是写死的 `1`，于是改伤害时既找不到、也没有测试守着。
     * ⚠️ 每颗子弹的出生点按**它自己的绝对角度**算（不是统一用 `a`）——
     *    否则三颗会在同一个点上重叠出发，看着像一颗。
     * ⚠️ 它们是**同帧全部射出**（不是连发三帧），与散射小怪的三发同一形态。 */
    var offs = fireAutoAngles(), i, ang;
    for (i = 0; i < offs.length; i++) {
        ang = a + offs[i];
        spawnPB(P.x + Math.cos(ang) * (P.half + 8),
                P.y + Math.sin(ang) * (P.half + 8),
                ang, BAL.player.bulletSpeed, playerAutoDmg(), 1, hasPassive(6));
        /*                                                          ↑ size  ↑ 被动 6「追踪弹」
         * ⚠️ `size` 显式写 1（与"不传"等价，见 `spawnPB`）—— 因为 `home` 在它后面，
         *    要跳过 `size` 只能靠占位，写出来比 `undefined` 清楚。
         * ⚠️⚠️ **追踪只在这里传 `true`**：三个技能走的是 `castSkill`，一个都不传
         *    （用户要的是"**普攻**子弹追踪"）。要改范围就改这一处。 */
    }
}
function castSkill(P, slot) {
    /* ⚠️⚠️ 参数是**槽位**（0 起），不是技能 id（`0.2.0` 修）。
     *    以前调用处传的是 `Save.loadout.active[slot]`（技能 id），
     *    而 `P.cds` 与 `hud.js` 都是**按槽位**索引的 ⇒ 两者只在
     *    "`active` 恰好是 `[0,1,2,…]`"时才相等。一旦玩家调整出战顺序，
     *    冷却就会**写到别的槽上**（表现：A 技能的冷却显示在 B 技能上、
     *    真正放的那招反而没进冷却）。加激光时正好要动这块，一并修正。 */
    var idx = Save.loadout.active[slot];
    if (idx === undefined) return false;
    var S = ACTIVES[idx];
    if (!S || P.cds[slot] > 0 || P.mp < S.cost) return false;
    P.mp -= S.cost;
    /* ⭐ **冷却缩减**（`0.2.0` 被动 3「冷却缩减」：`-50%`）。
     * ⚠️ 乘在**设值**这一处（不是读的时候减），所以 `hud.js` 里
     *    `cds / S.cd` 那个进度条的比例仍然是对的（分母用的是表里的 `S.cd`，
     *    但条是按"剩余 / 原始"画的，缩短后只是走得更快 —— 观感正确）。
     * ⚠️ 用 `Math.round` 到整帧：`cds` 是帧计数器（`cds[i]--`），
     *    小数会让它永远减不到 0（与普攻射速同一个坑，见 `autoFireCd`）。 */
    /* ⚠️ **本次实际冷却**（含极速项链的 -50% ✗）⇒ 同时记进 `cdMax` 给 HUD 当分母 ✔（单一来源 ✗） */
    var cdEff = Math.max(1, Math.round(S.cd * (hasPassive(3) ? 0.5 : 1)));
    P.cds[slot] = cdEff;
    P.cdMax[slot] = cdEff;
    /* ⭐⭐ **「冻结」**（`0.2.1`，第 5 个主动）：与激光一样"不射子弹"，但连判定区域都没有 ——
     *    它改的是**全局状态**（`Game.freeze` 计时器），效果全在 `update()` 的几处闸门上。
     *    ⚠️ 判据是 `freeze: true`（与 `laser: true` 同一套写法），**不看 `kind`** ——
     *      `kind: 'freeze'` 只是给数据读的，分支用布尔标记更稳（改 kind 名字不会坏）。
     *    ⚠️ 冷却已经在上两行设好了（`P.cds[slot] = …`）⇒ "**生效时冷却正常走**"自动成立，
     *      因为冻结**不会**去暂停 `P.cds` 的递减（见 `update()` 计时器那段的说明）。 */
    if (S.freeze) {
        Game.freeze = FREEZE.frames;
        return true;
    }
    /* ⭐⭐ **激光**（`0.2.0`）：第一个"不射子弹"的主动，单独分叉。
     * ⚠️ 它**不读** `count` / `spread` / `speed` / `size` —— 那些是弹丸的参数。
     * ⚠️ **方向在这一帧定死**（用户要求），之后无论玩家怎么动、鼠标怎么移都不变。
     *    所以要把角度**存下来**，不能每帧重算（每帧重算 = 激光跟着鼠标转）。
     * ⚠️ 长度也在这里先算一次：撞墙截断的结果**存下来**，
     *    这样玩家挪动时激光不会"突然变长又变短"（那是另一种抖）。
     *    代价：玩家如果把激光"甩"到掩体后面，激光**仍然画到原来的长度**
     *    —— 这是"方向固定"的合理代价，也与"放出去就不变了"的语义一致。
     *
     * ⭐⭐ **起点也一起存下来**（`0.2.0`，用户要求）：
     *    用户原话：**"确保激光发出后不要随着玩家平移（会导致激光'头'显得突兀，
     *    所以在那里用一个正方形表示激光源，即视觉上主角召唤的是激光源而非激光本身）"**。
     *    ⇒ 语义从"从玩家身上长出来的光束"改成"**放下的一个固定的激光源**"：
     *      · `ox / oy` 在放出那一帧定死，之后**判定与渲染都用它**，不再读 `P.x / P.y`
     *      · 起点**沿光束方向外移 `originOff`**（不是正好在玩家中心）——
     *        这样那个正方形源在**玩家身体外缘**，而不是压在主角身上。
     *    ⚠️⚠️ 第一版只有方向固定、起点仍跟着玩家 ⇒ 玩家一走，激光的"头"就
     *      从身体里拖出来一截（用户说的"突兀"）。改完才是"召唤了一个装置"。 */
    if (S.laser) {
        var a = Math.atan2(Input.aimY, Input.aimX);
        var originOff = P.half + LASER.originPad;
        /* ⚠️⚠️ **先算起点，再从起点量长度**（`0.2.0` 实测修的两处几何不一致）。
         *
         * ## 修之前是什么样
         *   · `laserReach` 从**玩家中心** `(P.x, P.y)` 量
         *   · 但渲染从**起点** `(ox, oy)` 画 `ox + len`
         *   ⇒ 起点比玩家中心前移了 `originOff = 18`，于是：
         *     1. **光束画得比能打到的远 18 像素**（视觉与判定不一致）
         *     2. **光束的头插进墙里 18 像素**（明明是"撞墙截断"，看着却穿墙了一点）
         * ## 修之后
         *   从 `(ox, oy)` 量 ⇒ `len` 的含义变成"**从起点算能打到多远**"，
         *   与渲染的 `ox + len` **逐像素一致**，截断点也正好落在墙边缘。
         * ⚠️ `LASER.len = 900` 现在是"**从起点算**的最远距离"（上限），语义更自洽。
         * ⚠️ 有效长度比修之前短 `originOff`（≈18px，占 2%）—— 这是**纯几何一致性**，
         *    没有动任何数值设计（伤害/时长/宽度/冷却都没变）。 */
        var ox = P.x + Math.cos(a) * originOff;
        var oy = P.y + Math.sin(a) * originOff;
        /* ⚠️⚠️ **两张联系人表必须在施法时清空**（`0.2.0`，用户实测报的 bug）。
         *
         * 用户原话：**"每次进关只有第一次有激光命中效果"**。
         * 根因：`laserContactNew` 是拿 `laserContactPrev` 比的，而那张表
         *    **在两次施法之间从来没清过** ⇒ 第一次激光留下的记录（敌人身份 / `'wall'`）
         *    还在里面 ⇒ 第二次施法第一帧一比就判成"已经在冒火了"
         *    ⇒ **整段激光一次火花都不冒**。
         *    ⚠️ 进关时两张表都是空的 ⇒ 于是**只有本关第一次正常** —— 与用户描述完全一致。
         * ⇒ 施法时把两张都置空：对新的一道激光来说，一切都算"首次接触"。 */
        /* ⚠️⚠️ **`+ 1` 是哨兵值，不是笔误**（`0.2.0` 修，用户为这件事报过两次）。
         *
         * ## 为什么必须多一格
         * 用户原话：**"我感觉激光动画消失得比设置的帧数快"**。
         *    根子在于我一开始把**两个不同的量**当成一个用：
         *      · **剩余帧数**（倒计时 `frames`）—— 会减到 0，而 `laserFade(0) = 0`
         *        ⇒ **倒计时归零那一帧画了却全透明** = 白占一帧、"看着提前没了"
         *      · **当前帧序号**（第几帧）—— 从 **1** 开始数，正好 `LASER.frames` 帧
         *    ⇒ 用 `frames: LASER.frames + 1`（倒计时 `21..1`）让两者对上：
         *      `当前帧序号 = LASER.frames + 1 - frames` ⇒ **1 … LASER.frames**
         *      而 `frames` 全程 `> 0` ⇒ `laserFade` 永远给得出 `> 0` 的不透明度
         *      ⇒ **光束从头到尾都看得见，不多不少 `LASER.frames` 帧**。
         *
         * ## 实测（`LASER.frames = 20`、`fadeFrames = 6`、淡出窗口 7 格）
         *    帧 1..13   剩余 20..8 → 见下（满亮段）
         *    帧 14..20  剩余 7..1  0.86 → 0.14（淡出段，最后两格更淡）
         *    ⇒ **总共 20 帧可见**，然后 `frames` 归零 → 置 `null` → DOM 隐藏。
         *
         * ⚠️⚠️ 我在这上面来回改了三次（`+1` → 不加 → 又 `+1`），每次都是因为
         *    "倒计时"和"帧序号"混着算。**以后要改时长，只动 `LASER.frames`，
         *    不要再给这个起点加偏移** —— 那个 `+1` 是哨兵，语义是"让倒计时永远 > 0"。 */
        /* ⚠️⚠️ **两张联系人表必须在施法时清空**（`0.2.0`，用户实测报的 bug：
         *    **"每次进关只有第一次有激光命中效果"**）。
         *
         * 根因：`laserContactNew` 是拿 `laserContactPrev` 比的，而那张表
         *    **在两次施法之间不会自己清** —— 上一道激光留下的记录（敌人身份 / `'wall'`）
         *    还在里面 ⇒ 第二道激光第一帧一比就判成"已经在冒火了"
         *    ⇒ **整段激光一次火花都不冒**。
         *    ⚠️ 进关时两张表都是空的 ⇒ 于是**只有本关第一次正常**，与用户描述完全一致。
         *    ⚠️ 实测证据：第 1 次施法 `laserContactPrev` 有 0 个键、第 2/3 次是 **1 个键**，
         *      接触判定从 `NEW` 变成 `old`，`laserSparks` 一次都没被调。
         * ⇒ 施法时把两张都置空：对新的一道激光来说，一切都算"首次接触"。
         * ⚠️ 这里**曾经漏掉过**（写注释时被连带替换掉了）—— 所以它有对应的回归断言。 */
        Game.laserContact = {};
        Game.laserContactPrev = {};
        P.laser = { ox: ox, oy: oy, angle: a, frames: LASER.frames + 1,
                    len: laserReach(ox, oy, a) };
        /* ⚠️⚠️ **这里曾经有一句 `pop(P.x, P.y, P_COLOR)`，`0.2.1` 删掉了** —— 详见本函数末尾那段。 */
        return true;
    }
    var base = Math.atan2(Input.aimY, Input.aimX);
    /* ⭐ 两类散射统一用**同一个角度公式**（原来两套、还不一样）：
     *      `a = base + (i - (count-1)/2) × spread`
     *   ⇒ 永远**关于瞄准方向对称**，`spread` 就是**相邻两发的夹角**（步长）。
     * ⚠️ 扇形的 `spread` 语义改成"步长"了（原先是"单侧总跨度的一半"，
     *    算出来是从 0° 扇到 2×spread、**不对称**）。所以它的数值也跟着改了，
     *    见 core.js 里那条说明。 */
    var size = S.size || 1;
    var i, a;
    if (S.kind === 'ring') {
        /* ⭐ 环形弹的角度相位。默认 `0.5` 会让第一发落在**两轴之间**（45° 附近），
         *    于是 4 个主方向（右/下/左/上，即 ±X / ±Y）**一发都没有**。
         * ⚠️ 用户 2026-10-01 明确要求："注意与坐标轴对齐，也就是有 4 发落在 4 个主方向"。
         *    ⇒ 相位改成 **0**：第一发沿 +X（右），之后每 2π/N 一发。
         * ⚠️⚠️ 要对齐就必须满足 `N % 4 === 0`（N 是弹数）。当前 N = 16 ✅。
         *    若以后把弹数改成 13 这种，`(i/N)*2π` 永远落不到 π/2 的整数倍上，
         *    对齐就没了 —— 改弹数时先算一下 `N % 4`。 */
        var RING_PHASE = 0;
        /* ⭐⭐ **施放前先清掉上一轮的环绕弹**（用户 2026-10-05："环绕弹改成再次使用后清除前面的" ✗）。
         *  ⚠️ 改之前是永久 + 可叠加 ✗ ⇒ 长局能堆到上百颗 ✔，而"环绕弹 × 敌弹"的抵消判定是
         *     两层循环 ⇒ 那段代价像平方增长 ✔。现在：新一轮顶掉旧的 ✗ ⇒ 场上始终只有一轮 8 颗 ✔。
         *  ⚠️ 只删 `orbit === true` 的 ✗ —— 普攻 / 散射 / 激光的子弹一颗不动 ✔；倒序遍历 ✔。
         *
         *  ⭐⭐ **相位顺着上一轮**（用户 2026-10-05："环绕技能(一关内)再次使用时，相位顺着之前的" ✗）：
         *     从场上的旧环绕弹**反推当前相位** ✗ —— 每颗都满足
         *     `orbitA = 相位 + orbitI × (2π / count)` ✗ ⇒ 拿任意一颗就能解出相位 ✔。
         *     ⚠️ 没有旧弹 ⇒ 用默认相位（首次施放 / 换关之后 ✗）✔
         *        ⇒ **换关自动回到初始相位** ✗，不需要额外的重置代码 ✔。 */
        var prevRingA = null;
        for (var pq = 0; pq < Game.pbullets.length; pq++) {
            var pb0 = Game.pbullets[pq];
            if (pb0 && pb0.orbit) { prevRingA = pb0.orbitA - (pb0.orbitI || 0) * (Math.PI * 2 / S.count); break; }
        }
        for (var q = Game.pbullets.length - 1; q >= 0; q--) {
            if (Game.pbullets[q] && Game.pbullets[q].orbit) Game.pbullets.splice(q, 1);
        }
        for (i = 0; i < S.count; i++) {
            /* ⭐⭐ 第 8 参 `blocks: true` —— **只有环形护体的子弹能打掉敌方子弹**
             *    （`0.2.1` 用户："把「环形护体」加强：对应的子弹碰到敌方子弹会与之抵消"）。
             *    ⚠️ 第 7 参 `home` 显式写 `false`：追踪是**普攻专属**的被动，
             *      技能弹一个都不追踪（见 `fireAuto` 那处说明）。 */
            /* 召唤时**均匀铺开**（8 发 ⇒ 0°, 45°, …, 315° 八个主方向 ✔） */
            /* ⚠️ 有上一轮 ⇒ **接着它的相位** ✗（每颗仍按等间隔均匀排开 ✔）；否则用默认相位 ✔。 */
            var ra = (prevRingA === null)
                ? (i / S.count + RING_PHASE) * Math.PI * 2
                : prevRingA + i * (Math.PI * 2 / S.count);
            var rb = spawnPB(P.x, P.y, ra, S.speed, S.dmg, size, false, true);
            /* ⭐ 打上"环绕"标记 ⇒ 更新段接管它的位置（不再自己往外飞 ✗）✔
             *    ⚠️ 每颗**各自**记角度 ⇒ 有子弹消失后**不补空、不重新均分** ✔（用户要求 ✗）。
             *    ⚠️ **永久存在** ✗（没有寿命字段 ✗）且**可叠加**（再放一次又 8 颗 ✔）。 */
            rb.orbit = true; rb.orbitI = i;   /* ⭐ 环上序号（反推相位要用 ✗） */
            rb.orbitA = ra;
            rb.orbitR = RING.r;
            /* ⭐⭐ **第一帧只定位、不推进角度**（用户 2026-10-05："初相不对，应为正上下左右 + 斜 45° 各一颗，
             *    现在有点偏顺时针几度" ✗）。根因：出生后第一帧就被 `orbitA += RING.omega` 推了一次 ✗，
             *    而 `RING.omega` = `2π/120` ⇒ **每帧 3°** ✔ ⇒ 首帧就"顺时针偏几度" ✔。
             *    ⇒ 加这个标记：**第一次更新只把它摆到召唤角度上** ✔，之后才正常转 ✔。 */
            rb.orbitFresh = true;
        }
    } else {
        /* 直射（count=1 时 `(count-1)/2 = 0` → 正好打在瞄准方向上）与扇形共用这条 */
        for (i = 0; i < S.count; i++) {
            a = base + (i - (S.count - 1) / 2) * S.spread;
            spawnPB(P.x, P.y, a, S.speed, S.dmg, size);
        }
    }
    /* ⚠️⚠️⭐ **施法不许在主角身上弹方块**（`0.2.1` 修，用户实测报的 bug）。
     *
     * 用户原话：**"主角用技能会在其位置出现一个黄色方块缩小的动画"**。
     * 那就是这里原来的一句 `pop(P.x, P.y, P_COLOR)`（激光分支里还有同样的一句，也删了）：
     *   · 尺寸/时长走 `pop` 的默认值 ⇒ **12 帧的渐缩方块**，正好落在玩家身上
     *   · 颜色 `P_COLOR` 是**黄**，而黄在本作里的语义是"**我打中了**"
     *     （见 `PLAYER_HURT` 那段：黄=我在打 / 红=我被打），
     *     出现在自己身上会被读成"我挨了一下"或者"角色被一块东西盖住了"
     * ⇒ 与 `0.2.0` 删掉"受伤红方块"（`hurtPlayer` 里那句）**是同一条理由**：
     *   **方块特效是"命中"的语言，不是"我做了个动作"的语言。**
     * ⚠️ 施法本来就有的表达够用了：子弹/弹幕从身上出去，激光还有那个固定的源方块
     *    （`P.laser`，见上），玩家一眼能看出技能放没放出来。
     * ⚠️ 用户对 `pop` 的评价还有一句更直接的：**"回血回蓝药也用火花特效，不用 pop，
     *    那个基本看不到"** —— 药那边 `0.2.0` 已经换成火花了，技能这边本来就该跟上。
     * ⇒ **以后要给施法加反馈，别用 `pop`**（它不是施法的语言）；真要加就加
     *   "从玩家身上扩出去"的环/光，并且让它能被 `test-logic` 第 4 节那条断言看见
     *   —— 那里守着"放技能后 `Game.fx` 必须是空的"。 */
    return true;
}

