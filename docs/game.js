/* ⭐⭐ **玩家受伤的唯一入口**（`0.2.0` 起全部伤害都走它）。
 * `n` = 伤害值。
 * ⚠️ 判"有没有被打到"一律看这里的 `P.inv` 与 `P.hp`，不要在调用点各写一套。 */
function hurtPlayer(n) {
    var P = Game.player;
    /* ⭐⭐ **冻结期：主角不受任何伤害**（`0.2.1` 第 5 个主动「冻结」）。
     *    用户原话："**且此时主角不受伤害（碰到子弹或敌人不触发，但碰撞情况与原来一样）**"。
     *
     * ⚠️⚠️ **闸门就设在这里**，因为它是**全部伤害的唯一入口**：
     *    接触伤害（敌人压上来）、敌弹命中、BOSS2 光束，全都调 `hurtPlayer`
     *    ⇒ 在这一处返回，等于"子弹/敌人/激光碰到你都不触发"，**不用去三个地方各加一个 if**
     *      （那种写法以后加第四种伤害来源必然漏一个）。
     * ⚠️ 冻结期**连无敌帧也不消耗**（直接 return，不改 `P.inv`）——
     *    否则解冻瞬间你会因为"无敌帧刚好用完"而立刻挨一下。
     * ⚠️ **碰撞本身没变**：敌人照样挡路、`pushApart` 照样把你顶开 ——
     *    那些都在 `update()` 的敌人段里，**不经过这里**（用户要的"碰撞情况与原来一样"）。 */
    if (Game.freeze > 0) return;
    P.hp -= n;
    /* ⚠️ **只留无敌帧闪烁，不弹红方块**（用户 2026-10-01 定）。
     *    这里曾经有 `pop(P.x, P.y, E_COLOR)` —— 那是**敌人色**（`#e05a5a`）的方块，
     *    打在玩家身上会被读成"有个敌人/爆炸在我身上"，与"我受伤了"混淆
     *    （用户原话："玩家受伤时不要变成红色，会混淆"）。
     *    受伤的既有表达是 `P.inv` 驱动的**闪烁**（见 render 里玩家绘制那段），够清楚了。
     * ⭐ 被动「无敌时间」（下标 6）在这里追加帧数：基础 48 + 48 = 96 帧（1.6 秒）。
     *    ⚠️ 用 `hasPassive` 读**当前出战配置**，所以进关中途改配置不会立刻生效 ——
     *      那是既有的规则（所有被动都是进关时读一次），不是这里的问题。 */
    P.inv = BAL.player.iframe * (hasPassive(2) ? 2 : 1);
}

/* 退出关卡 → 回**选关屏**（layer2），与结算框的「回选关」按钮同一个去处。
 *
 * ⚠️ **不走 endLevel()**。endLevel 会结算经验/金币、并把 mode 置为 'result'，
 *    那是"通关/失败"的路径；中途退出**不该给奖励**，也不该弹结算框。
 *    这里只做三件事：清战斗残留 → 复位状态 → 切回选关屏。
 *
 * ⚠️⚠️ **收尾必须复用 `UI.toSelect()`，不要自己算层号**：
 *    曾经这里写 `changeLayer(SELECT_LAYER)`，而 `SELECT_LAYER` 被写成了 1，
 *    结果 Esc 退出跑到了**标题界面**（layer1），不是选关屏（layer2）。
 *    现在统一走 `UI.toSelect()`——它同时负责 changeLayer(2) 和刷新选关屏数据，
 *    与「回选关」按钮**完全一致**，不会再出现两套逻辑走岔。
 *    （ui.js 在 game.js 之前加载，但本函数只在运行期被调用，所以能引用到 UI。） */
function quitToSelect() {
    /* 追踪：这个函数是**唯一**把玩家送回选关的路径（除了切标题），
     *    所以「偶发跳回选关」一定要在这里留下记录（见 trace.js 顶部说明）。 */
    if (typeof Trace !== 'undefined') Trace.add('quitToSelect', 'mode=' + Game.mode + ' 敌=' + Game.enemies.length + ' 关=' + Game.levelId);
    Game.mode = 'idle';
    Game.enemies = [];
    Game.ebullets = [];
    Game.pbullets = [];
    Game.fx = [];
    /* ⚠️ 激光命中火花同理（`0.2.0`）：不清会把上一关的火花带进下一关。 */
    Game.sparks = [];
    Game.beams = [];             /* ⚠️ BOSS2 的光束同理（`0.2.1`）：不清会带进下一关继续打人 */
    /* ⭐ **「冻结」计时器同理**（`0.2.1`）：不清的话"上一关最后 3 秒的冻结"会带进下一关
     *    （表现：刚进关敌人就不动、而且你不受伤害 —— 静默地把难度改掉）。 */
    Game.freeze = 0;
    Game.laserContact = {};
    Game.laserContactPrev = {};
    Game.result = null;
    Game.resultPending = null;   // ⚠️ 同 startLevel：别把结算倒计时留到下一关
    /* ⚠️⚠️ **波次倒计时同理**（`0.2.1`）：不清的话，"本波清完 → 下一波"的那段倒计时
     *    会在**已经回到选关之后**走完，然后 `spawnNextWave()` 往场上塞一批敌人
     *    （而那时 `Game.mode` 已经是 idle ⇒ 看不见、但状态脏了；再进关会带上这一批）。
     *    ⚠️ 与 `resultPending` 完全同一类坑（一次性标志没清），所以放在一起。 */
    Game.wavePending = null;
    /* ⚠️ 击杀奖励累计同理（`0.2.0`）：不清会把上一关的钱带进结算。 */
    Game.killExp = 0;
    Game.killGold = 0;
    /* ⚠️ 玩家死亡状态同理：不清的话下一关一进去玩家就是不画的
     *    （`Game.playerDead` 是持久状态，只在 `startLevel` 与本函数复位）。 */
    Game.playerDead = false;
    Game.playerDeathT = 0;
    _obsCache = null;
    if (typeof invalidateStaticLayer === 'function') invalidateStaticLayer();   /* ⭐ 静态层跟着一起失效（0.3.0） */
    Input.useSkill = -1;
    Input.useItem = false;
    Input.exit = false;
    Input.firing = false;
    document.getElementById('result').classList.add('hidden');
    document.body.classList.remove('result-show');
    UI.toSelect();                  // 与「回选关」按钮同一条路径（见上）
}


