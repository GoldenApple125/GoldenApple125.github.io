/* ⭐ **槽位的"当前这一档"价格**（`0.2.1`）。
 *    `owned` = **已经买过几档**（初始 2 槽时是 0）。
 *    ⚠️ 返回 **0 = 没得买了**（已到 `MAX_*_SLOTS`）—— 调用方就拿它当"禁用"判据，
 *       **不要再另写一个 `Save.maxActive >= MAX_ACTIVE_SLOTS`**：两处判"满"必然不同步
 *       （而"价格表长度"与"上限"本来就由上面那条断言绑在一起）。 */
function slotPrice(kind, owned) {
    var t = BAL.price[kind];
    return (t && owned >= 0 && owned < t.length) ? t[owned] : 0;
}

