/* ⭐⭐ **BOSS4 招式 3：4 发大环绕弹**（`0.3.1` ✗，用户 2026-10-05）：
 *   **"4发大环绕弹，可抵消玩家子弹(不抵挡激光)，若碰到玩家造成伤害2"** ✔
 *
 * ⚠️ 做法 ✗：往 `Game.ebullets` 里推 4 发**带 `orbit` 标记**的大弹 ✔（体型 ×2 = 28×28 ✗、伤害 2 ✗），
 *     位置**不靠速度**，而由敌弹循环里那段 "orbit 更新" 每帧摆到**绕本体公转**的角度上 ✔
 *     （本体只在关卡开始时慢慢漂移 ✗ ⇒ 整圈会跟着它走 ✔）。
 * ⚠️ 初速给 0 ✗、角度从正右起每 90° 一发 ✔（四发正好均分 ✗）。
 * ⚠️ `life` 先按 `orbitFrames`（300 帧 = 5 秒 ✗）写上 ✔；
 *     ⚠️ 若敌弹的存活字段其实叫别的名字 ✗，第 ④ 步读循环时**按真实字段名纠正** ✔（不猜 ✗）。
 * ⚠️ 与玩家的环绕技能**不共用任何常量** ✔（各自独立 ✗）。 */
function boss4Orbit(E) {
    /* ⭐⭐ **相位延续** ✗（用户 2026-10-05："环绕弹类似玩家，一关内再次放顺着相位" ✔）：
     *  ⚠️ 先读旧弹里**任意一颗**的当前角度当基准 ✔（四发本来就差 90° ✗ ⇒ 谁当基准都对 ✔），
     *     没有旧弹时基准取 0 ✔ ⇒ "再放"时新弹**正好落在旧弹原位**，肉眼看不到跳相 ✔。
     *  ⚠️ 与玩家的环绕技能同一套思路 ✗（那边是从旧弹反推相位 ✔）。 */
    var baseA = BOSS4_SHOT.orbitPhase0, q0, b0;   /* ⭐ 初相 = 4 个正向 ✔（有旧弹时下面会被覆盖 ⇒ 顺相位 ✗） */
    for (q0 = 0; q0 < Game.ebullets.length; q0++) {
        b0 = Game.ebullets[q0];
        if (b0.orbit && b0.orbitOwner === E) { baseA = b0.orbitA; break; }
    }
    /* ⭐ **再清掉自己上一轮留下的环绕弹** ✗（旧弹不该自己消失，也不该越积越多 ✔
     *    ⇒ **同一只本体再放这一招 = 替换** ✔）。⚠️ 必须放在读基准**之后** ✗。 */
    for (var q = Game.ebullets.length - 1; q >= 0; q--) {
        var ob = Game.ebullets[q];
        if (ob.orbit && ob.orbitOwner === E) Game.ebullets.splice(q, 1);
    }
    var n = BOSS4_SHOT.orbitCount, i;      /* ⭐ 4 → 8 ✗（常量控制 ✔） */
    for (i = 0; i < n; i++) {
        var a = baseA + i * BOSS4_SHOT.orbitStep;   /* ⭐ 顺着旧相位 ✔ + 每 45° 一发 ✗ */
        var b = spawnEB(E.x + Math.cos(a) * BOSS4_SHOT.orbitR,
                       E.y + Math.sin(a) * BOSS4_SHOT.orbitR, 0, 0,
                       E.bulletHalf * BOSS4_SHOT.orbitSizeMul, BOSS4_SHOT.orbitDmg);
        if (!b) continue;
        b.orbit = true;
        b.orbitOwner = E;
        b.orbitA = a;
        b.orbitFresh = true;      /* ⭐⭐ **出生那一帧不转** ✗（用户 2026-10-05："刚召唤出来就转了一次导致不是正上" ✔）：
                                   *    ⚠️ 与玩家的环绕弹**同一套** ✗（那边是 `if (b.orbitFresh) … else b.orbitA += RING.omega` ✔）；
                                   *    不加这个 ⇒ 召唤当帧先转 1.5°（90°/秒 ÷ 60 ✗）⇒ 半径 72 下偏 ≈1.9px ⇒ 看着不是正上 ✔。 */
        /* ⚠️ 不写存活倒计时 ✗（用户没要 ✗）：被吃掉 / 再放替换 / 本体死亡时才消失 ✔ */
    }
}

