/* ⭐⭐ **道具"现在用得上吗"**（`0.3.0`，用户 2026-10-02："道具也做对应的（如满血/数量 0）变灰"）。
 *    · `hp` = 带了回血药 **且没满血**；`mp` = 带了回蓝药 **且没满蓝**；
 *    · 数量为 0 / 没带 / 已经满了 ⇒ 对应项为假 ✔。
 * ⚠️⚠️ **必须定义在顶层**（`update()` **之外**）：`hud.js` 的"按键字母要不要变灰"要调它，
 *    而我第一版把它写在了 `update()` **体内** ✗ —— 缩进是 0、但作用域是嵌套的 ⇒
 *    `hud.js` 里的 `typeof itemWant === 'function'` **恒为假** ✗ ⇒ 一直走兜底"有药就算可用"
 *    ⇒ 症状正是用户报的"**用光变灰、满血不变**"（用光时 `itemLeft = 0`，兜底也判假 ⇒ 灰 ✔）✗。
 *    ⚠️ 这个坑本项目踩过**第三次**了（`render()` 里的静态层那一族、`HUD` 对象字面量里的函数）——
 *      记一条硬规矩：**要被别的文件调用的函数，一律写在文件顶层**（缩进 0 ≠ 顶层 ✗）。
 * ⚠️ 判据只有**一处**：`update()` 里真正"用掉"的那段与 HUD 读的是同一个函数 ✔
 *    ⇒ 不会出现"看着是灰的却能用 / 亮着却用不了"的错位 ✗。
 * ⚠️ 返回**两个布尔**而不是一个"能不能用"：真正用的时候要知道**补哪一项** ✔。 */
function itemWant(P) {
    var IDX = (typeof Save !== 'undefined' && Save.loadout) ? Save.loadout.item : -1;
    var I2 = (typeof ITEMS !== 'undefined' && IDX >= 0) ? ITEMS[IDX] : null;
    if (!I2 || !P || !(P.itemLeft > 0)) return { hp: false, mp: false };
    return { hp: (I2.heal > 0 && P.hp < P.hpMax), mp: (I2.mp > 0 && P.mp < P.mpMax) };
}

function update() {
    if (Game.mode !== 'play') return;
    var P = Game.player;

    /* --- 结算倒计时（胜负已定，但还没弹结算框） ---
     * ⭐ 见 `BAL.resultDelay` 的说明。用户要求"延迟一个固定时间"，不要绑定敌人动画。
     * ⚠️ **不能改成 `setTimeout`**：主循环是固定步长累加器，用帧计数才与游戏时间同源，
     *    截图 / 暂停 / 后台切回时行为才一致（本项目所有计时都走帧）。
     *
     * ⚠️⚠️ **这里只递减计数、不 return**（`0.2.0` 第四版改的）。
     *    前三版都在这里 `return`（自称"冻结关卡"），结果**每次都是同一个症状**：
     *    · 特效冻在渐缩中途 → "缩到一半卡住"
     *    · 改成"锁成满尺寸" → "满尺寸僵 0.6 秒"
     *    · 甚至删掉冻结分支后**问题依旧** —— 因为真正在冻的是**这个提前 return**
     *      （特效循环写在它后面，永远跑不到，`t`/`hold` 一帧都不变）
     *
     * **正确规则**：我没有权力替玩家决定"胜负已定就别再动了"。
     *    ⇒ 倒计时期间**关卡照常跑**（特效、子弹、敌人、玩家全都正常），
     *      只是**结算框晚 0.6 秒弹**。玩家看到的是一段正常的收尾，
     *      而不是一张突然冻住的画。
     *    ⚠️ "已经在赢的路上被残留敌弹反杀"由下面 `!Game.resultPending` 挡住 ——
     *      不会先弹胜利再改成失败。 */
    if (Game.resultPending && --Game.resultPending.t <= 0) {
        var won = Game.resultPending.win;
        Game.resultPending = null;
        /* ⚠️ `Game.playerDead` **不在这里清**（`endLevel` 也不清）——
         *    它是"这个人已经死了"的持久事实，清掉会让玩家在结算框背后重新出现。
         *    只在 `startLevel` 里复位。 */
        endLevel(won);
        return;      /* 本帧到此为止：已经进结算了，别再跑关卡逻辑 */
    }

    /* --- 波次间隔倒计时（本波清完 → 下一波） ---
     * ⭐ 时长与结算延迟**用同一个数**（`BAL.resultDelay`，用户指定："这个'1点时间'
     *    先设置成相当于'弹窗延迟'的时间"）⇒ 以后调那一个数，两边一起变。
     * ⚠️ 与结算倒计时**同一个理由**不用 `setTimeout`：主循环是固定步长累加器，
     *    帧计数才与游戏时间同源（截图 / 暂停 / 后台切回时行为一致）。
     * ⚠️ 这里**也不 return**：倒计时期间关卡照常跑（残留子弹、特效、玩家移动都正常），
     *    只是"下一波还没出来"—— 与结算延迟那条的处理保持一致。 */
    if (Game.wavePending && --Game.wavePending.t <= 0) {
        Game.wavePending = null;
        spawnNextWave();      /* 定义在 level.js（它才知道关卡/地图数据与刷怪约束） */
    }

    /* --- 玩家死亡渐缩（纯表现，`BAL.deathFrames` 帧） ---
     * ⭐ 与 `resultPending` **各自独立**：
     *    · `resultPending` 管"什么时候弹结算框"
     *    · `playerDeathT` 管"死亡动画播到第几帧"
     * ⚠️ 合成一个曾经出过 bug：`endLevel` 清掉 `resultPending` 后，
     *    "玩家已死"的判据跟着变 false ⇒ 玩家**又在结算框背后冒出来**
     *    （用户实测："有时主角失败消失，在弹窗后又出现"）。
     * ⚠️ 死亡动画期间关卡**照常跑**（同结算延迟的原则：不冻结画面），
     *    否则动画根本播不动。 */
    if (Game.playerDeathT > 0) Game.playerDeathT--;

    Game.frames++;
    readIntent();

    /* --- 退出关卡（Esc 或 HUD 按钮） ---
     * ⚠️ 必须放在**最前面**并直接 return：否则这一帧还会继续跑移动、
     *    甚至因为"敌人清空"而误判通关（退出却被记成通关）。
     * ⚠️ 一次性标志要在**任何分支下**都清掉，不然会残留到下一关，
     *    导致刚进关就被踢出去。 */
    if (Input.exit) {
        Input.exit = false;
        quitToSelect();
        return;
    }

    /* --- 移动（摩擦力驱动，便于与碰撞解耦） --- */
    var targetVx = Input.moveX * P.move, targetVy = Input.moveY * P.move;
    P.vx += (targetVx - P.vx) * 0.35;
    P.vy += (targetVy - P.vy) * 0.35;

    var obs = obstacles(), i, j;
    /* ⭐ 子步进（防隧穿）：把本帧位移拆成若干小步，每步不超过半个半径。
     * 否则高速时一帧能整个跨过 80px 的方块 → 直接"穿墙"
     * （实测被测试抓到：tunnel = 7）。
     * 正常速度（4.2/帧）时 steps = 1，**没有任何额外开销**。 */
    var mVx = P.vx, mVy = P.vy;
    var steps = Math.ceil(Math.max(Math.abs(mVx), Math.abs(mVy)) / (P.half * 0.5));
    if (steps < 1) steps = 1; else if (steps > 16) steps = 16;
    for (var st = 0; st < steps; st++) {
        // ⚠️ 用 moveWithCollision（含"接受检查"），不要直接 separateFromRects：
        //    相邻两块墙会产生乒乓死循环，见 moveWithCollision 的说明。
        // ⚠️ 也不要在这里再写"世界边界钳制"：边界已是 obs 里的 4 面墙。
        moveWithCollision(P, mVx / steps, mVy / steps, obs);
    }
    // 兜底：分离后仍越界（理论上不会，边界墙很厚）则钳回
    if (P.x < P.half) P.x = P.half;
    if (P.x > LOGICAL_W - P.half) P.x = LOGICAL_W - P.half;
    if (P.y < P.half) P.y = P.half;
    if (P.y > LOGICAL_H - P.half) P.y = LOGICAL_H - P.half;
    // 记录"最后确认合法的位置"：物体被挤进墙里时按它脱困
    if (worstPenetration(P, obs) <= 0.01) { P.safeX = P.x; P.safeY = P.y; }

    /* --- 计时器 --- */
    if (P.inv > 0) P.inv--;
    if (P.fireT > 0) P.fireT--;
    /* ⚠️⚠️ 长度用 `P.cds.length`，**不能写死 3**（`0.2.0` 修）。
     *    加了第 4 个主动后，写死 3 会让 `cds[3]` **永远不被递减**
     *    ⇒ 激光放一次之后**冷却不会再走完**（表现："第 4 个技能只能放一次"）。
     *    ⚠️ 而且这个 bug 与 `newPlayer` 里那个"长度写死 3"是**同一个坑的两半**：
     *      那边读不到值 ⇒ 无冷却；这边不递减 ⇒ 冷却卡死。修一个不修另一个都还是坏的。 */
    for (i = 0; i < P.cds.length; i++) if (P.cds[i] > 0) P.cds[i]--;
    /* ⭐⭐ **「冻结」倒计时**（`0.2.1`）。
     *    ⚠️ 它与 `P.cds` **各走各的** —— 用户明确要求"**生效时冷却正常走**"，
     *      所以这里**不要**写成"冻结时跳过冷却"（那是很多人对"时停"的直觉，但用户要的不是）。
     *    ⚠️ 放在**这一处（主循环的计时器段）**，不在敌人段里：冻结是**全局状态**，
     *      与敌人数量无关（敌人都死光时它照样该走完）。 */
    if (Game.freeze > 0) Game.freeze--;

    /* --- 恢复 ---
     * ⭐ `0.2.0` 改为**按最大值的百分比**回复（用户定）：
     *    · 被动 0「生命回复」每秒 **1% 最大生命**
     *    · 被动 1「能量回复」每秒 **5% 最大能量**
     * ⚠️ 用 `/ 60` 把"每秒"摊到每帧（帧率固定 60，见 core.js 的 `STEP_MS`）。
     * ⚠️ `Math.min` 夹在上限内 —— 满血/满蓝时不会溢出（原来那条"满蓝不溢出"的
     *    测试守的就是这里）。
     * ⚠️⚠️ **两种回复的基准也不同**，别写成同一个：
     *    生命是按**上限的百分比**（所以升级涨上限、回血也更快），
     *    能量同理。旧版是"固定 0.5 生命/秒"，与上限无关。 */
    if (hasPassive(0)) P.hp = Math.min(P.hpMax, P.hp + P.hpMax * 0.01 / 60);
    P.mp = Math.min(P.mpMax, P.mp + (P.mpRegen / 60) + (hasPassive(1) ? P.mpMax * 0.05 / 60 : 0));

    /* --- 主输出：按住左键自动开火 ---
     * ⭐ 射速走 `autoFireCd()`（被动 4 / 5 改它），**不要**直接写 `BAL.player.fireCd`。 */
    if (Input.firing && P.fireT <= 0) { fireAuto(P); P.fireT = autoFireCd(); }

    /* --- 技能（本帧请求，一次性） --- */
    if (Input.useSkill >= 0) {
        var slot = Input.useSkill;
        var sk = Save.loadout.active[slot];
        /* ⚠️⚠️ 解锁判定走 `skillUnlocked`（`0.2.0` 起有两种解锁方式：等级 / 打 BOSS）。
         *    原来写的是 `sk < Save.unlocked` —— 那个计数**不含 BOSS 解锁的激光**
         *    （见 `recalcUnlocked`），用它判会让激光**永远放不出来**。 */
        if (sk !== undefined && skillUnlocked(sk)) castSkill(P, slot);
        Input.useSkill = -1;
    }

    /* --- 道具 ---
     * ⭐⭐ **按"带的那个道具"决定回复什么**（`0.2.0`，用户定：加回蓝药）。
     *
     * 用户原话：**"回血药改成回 5 点，加入回蓝药（8 点），还是只能带一个"**。
     * ⚠️ **不写 `if (Save.loadout.item === 1)`** —— 改成读道具自己的字段
     *    （`heal` / `mp`），以后加第 3 个道具只需要往 `ITEMS` 里加一行数据。
     * ⚠️⚠️ **"用不上就不消耗"**：回血药在满血时按 E **不扣次数**、也不弹特效。
     *    回蓝药同理（满蓝时用不掉）。这条以前就成立（`P.hp < P.hpMax`），
     *    现在两个道具合流，判据变成一个函数式的"**回复量 > 0**"——
     *    否则会出现"满血时按 E 把回蓝药浪费掉"这种坑。
     * ⚠️ 特效颜色按道具分：回血绿、回蓝蓝（沿用原来的 `#7de07d`）。
     * ⚠️⚠️ **用的是"火花"特效，不是 `pop`**（`0.2.0` 用户要求）。
     *    用户原话：**"回血回蓝药也用火花特效，不用 pop，那个基本看不到"**。
     *    原因：`pop` 是**单个方块、从大缩到小**，贴在玩家身上时几乎被玩家自己盖住、
     *    又只持续 12 帧；而火花是**一次爆开 6 颗、向外飞散**，在角色周围很明显。
     *    药品是"我要确认它生效了"的操作 ⇒ 反馈必须看得见。
     *    ⚠️ `dimHex` 取同色相的暗色当碎屑 —— 与激光火花同一套配色逻辑
     *      （见 `laserSparks` 的说明：碎屑是"同一个东西的碎屑"，不是另换一个颜色）。 */


    if (Input.useItem) {
        Input.useItem = false;
        var IT = ITEMS[Save.loadout.item];
        if (IT && P.itemLeft > 0) {
            /* ⚠️ 判据走**共享函数** `itemWant()` —— HUD 的"按键数字变灰"读的是同一个 ✔ */
            var want = itemWant(P);
            var wantHp = want.hp;
            var wantMp = want.mp;
            if (wantHp || wantMp) {
                P.itemLeft--;
                if (wantHp) P.hp = Math.min(P.hpMax, P.hp + IT.heal);
                if (wantMp) P.mp = Math.min(P.mpMax, P.mp + IT.mp);
                /* ⚠️ 颜色**先存进变量**再传给两次调用：`IT.mp > 0 ? … : …` 写两遍
                 *    就会出现"主闪和碎屑用了不同颜色"的不一致（写错一处很难发现）。 */
                var itemC = (IT.mp > 0) ? PAL.mpItem : PAL.heal;
                laserSparks(P.x, P.y, itemC, dimHex(itemC, LASER_SPARK_DIM));
            }
        }
    }

    /* --- 敌人 --- */
    /* ⭐⭐ **冻结期：敌人的"动作"全停**（`0.2.1`，第 5 个主动）。
     *    ⚠️⚠️ 这里**只掐三件事**（速度累积 / 开火计时 / 招式计时），
     *      **碰撞与推挤照常**（下面的 `aabbOverlap` / `pushApart` / 脱困那几段**不动**）——
     *      用户原话："碰到子弹或敌人不触发，但**碰撞情况与原来一样**"
     *      ⇒ 冻住的敌人**仍然是实体**，照样挡你的路、照样能把你顶开。
     *    ⚠️ 做法是"速度归零 + 计时不走"，**不是** `continue` 跳过整段 ——
     *      跳过的话碰撞和推挤会一起没掉，那就不是"碰撞情况与原来一样"了。 */
    var frozen = Game.freeze > 0;
    for (i = 0; i < Game.enemies.length; i++) {
        var E = Game.enemies[i];
        var dx = P.x - E.x, dy = P.y - E.y, dl = Math.sqrt(dx * dx + dy * dy) || 1;
        /* ⭐ **BOSS 保持距离**（`0.2.0`）：离玩家太近就**不再压上去**。
         *
         * ⚠️ 为什么必须加这一条：小怪的策略是"一路贴上去"（靠接触伤害），
         *    而 BOSS 是 **60 血 + 弹幕型**——如果照搬贴脸，玩家会被 2 点接触伤害
         *    持续磨死，弹幕反而成了次要威胁，而且 BOSS 体型 56×56 会把玩家挤在角落。
         * ⚠️ 用"把移动目标速度乘 0 比例"来实现，**不改 `E.move`** ——
         *    改 `E.move` 会污染它自己的数值（`E.move` 是种类表拷来的原始值，
         *    以后想读"这只 BOSS 该多快"会读到被改过的数）。
         * ⚠️ 阈值写死在这里而不是加字段：目前只有一种 BOSS，加字段是过度设计；
         *    真要做第二种再挪进 `ENEMY_TYPES`。 */
        var creep = E.move;
        if (E.boss && dl < 170) creep = 0;
        /* ⚠️ 冻结期：**不累积速度**（并把已有的速度清掉）⇒ 它这一帧一动不动。
         *    下面的 `moveWithCollision` / 撞墙滑动**照常跑**（位移是 0，白跑一遍但无害），
         *    这样"碰撞与推挤"那几段一行都不用改。 */
        if (frozen) { E.vx = 0; E.vy = 0; } else {
            E.vx += ((dx / dl) * creep - E.vx) * 0.06;
            E.vy += ((dy / dl) * creep - E.vy) * 0.06;
        }
        /* 敌人同样做子步进（与玩家一致），避免高速穿墙 */
        var eSteps = Math.ceil(Math.max(Math.abs(E.vx), Math.abs(E.vy)) / (E.half * 0.5));
        if (eSteps < 1) eSteps = 1; else if (eSteps > 16) eSteps = 16;
        E.x += E.vx / eSteps; E.y += E.vy / eSteps;
        moveWithCollision(E, 0, 0, obs);      // 分离（接受检查内建）
        /* 敌人撞墙后要能"滑"过去，否则会一直顶着墙不动（实测踩过） */
        for (j = 0; j < obs.length; j++) {
            /* 撞墙后沿切向滑（去掉朝墙的速度分量），否则会一直顶着墙不动 */
            var em = aabbRectMTV(E, obs[j]);
            if (em) {
                var nl = Math.sqrt(em.x * em.x + em.y * em.y);
                if (nl > 0.001) {
                    var nxx = em.x / nl, nyy = em.y / nl;
                    var vn = E.vx * nxx + E.vy * nyy;
                    if (vn < 0) { E.vx -= vn * nxx; E.vy -= vn * nyy; }
                }
            }
        }
        // 边界在 obs 里（4 面厚墙），不需要额外钳制

        /* ⭐ **BOSS2 招式 2 的第二波**（`0.2.1`）：第一波打完时记了 `volleyT` + `volleyAim`，
         *    这里每帧递减，到点再打一波。
         * ⚠️⚠️ **用的是第一波留存的 `E.volleyAim`，不是这一帧的 `atan2(dy, dx)`**
         *    （用户："**让两波弹的第二波不要独立'瞄准'，与第一波的瞄准情况同步**"）。
         *    ⇒ 中途玩家跑开，第二波**照样**沿第一波的方向打 —— 两波是"同一个扇形的两个时间差版本"，
         *      第二波才能正好补第一波的缝（各瞄各的话，缝会随玩家移动而错位）。
         * ⚠️ `volleyAim` 与 `volleyT` 是**同一次开火里一起写**的（见 `boss2Fire`）⇒
         *    走到这里时它一定有值，**不需要**"万一没值就回退"的那种守卫。
         * ⚠️ 用 `> 0` 做前置判断，不用 `!== undefined`：`makeOne` 出来的敌人没有这个字段，
         *    未定义时整段跳过（与 `b.home` 那条同一个写法）。 */
        if (!frozen && E.volleyT > 0 && --E.volleyT <= 0) {
            /* ⚠️ 第二波传下标 **1**（`±7.5 / ±22.5 / …`，10 发 —— 正好补第一波的缝）。 */
            boss2Volley(E, E.volleyAim, 1);
            E.volleyT = 0;
        }

        /* ⚠️ 冻结期：**开火间隔也不走**（`E.fireT` 不减），且**不许开火**。
         *    ⚠️⚠️ `E.fireT <= 0` 那个条件**必须也加 `!frozen`**：如果冻结正好发生在
         *      `fireT` 已经归零的那一刻，只掐递减的话它会**每帧都开火**（比不冻结还猛）。 */
        /* ⭐ BOSS3 招式 1 的第二波（30 帧后 ✗）：冻结期同样不走 ✔ */
        if (!frozen && E.boss3T > 0 && --E.boss3T <= 0) boss3Ring2(E);
        /* ⭐ BOSS4 招式 2 第二组（插空 8 道 ✗）延迟 30 帧 ⇒ 这里倒数 ✔（与 boss3T 同一套 ✗）*/
        if (!frozen && E.boss4T > 0 && --E.boss4T <= 0) boss4Beams2(E);
        if (!frozen) E.fireT--;
        if (E.fireT <= 0 && !frozen) {
            /* ⭐⭐ **BOSS 走专属弹幕**（`0.2.0`）：环形 ←→ 瞄准散射**交替**。
             *    与小怪那套"按 count/spread 打一发"不同，所以在这里分叉。
             * ⭐ `0.2.1` 起多了 **BOSS2**（`boss2: true`）：招式是"三道激光 ←→ 连发两波大子弹"，
             *    与 boss1 完全不同 ⇒ 在 `boss` 之前再分一次叉（顺序不能反：
             *    BOSS2 同时带 `boss` 标记，先判 `boss` 的话它会去打环形弹幕）。 */
            if (E.beam) { mobBeamFire(E, dx, dy); }   /* ⚠️⚠️ **必须与下面连成一条 `else if` 链** ✗：
            /* 曾经它是独立的 `if` ✗ ⇒ 小怪 6 放完光束后**又会掉进最底下的通用分支** ✔
             *  ⇒ 用户实测："小怪6现在有多出发射普通子弹的bug" ✔ ⇒ 现已接成一条链 ✔。 */
            else if (E.boss4) {
                /* ⭐ BOSS4 三招依次循环 ✗：0 = 3 发大追踪弹、1 = 正 8 向激光、2 = 4 发环绕弹 */
                var p4 = E.boss4Phase || 0;
                if (p4 === 0) boss4Aimed(E, dx, dy);
                else if (p4 === 1) boss4Beams(E);
                else if (typeof boss4Orbit === 'function') boss4Orbit(E);   /* ⚠️ 招式 3 待实现 ✗ ⇒ 先守卫，避免 ReferenceError ✔ */
                E.boss4Phase = (p4 + 1) % 3;
            }
            else if (E.boss3) { boss3Fire(E, dx, dy); }
            else if (E.boss2) { boss2Fire(E, dx, dy); }
            else if (E.boss) { bossFire(E, dx, dy); }
            else if (E.cross) {
                /* ⭐⭐ **十字**（`0.2.1`，怪物 3）：**固定朝 4 个正方向**各打 1 发，共 4 颗。
                 *
                 * 用户原话：**"固定朝十字发射子弹（1次共4颗）"** ——
                 * ⚠️⚠️ 关键是"**固定**"：**不读 `dx/dy`、不瞄准玩家**。
                 *    所以这里**不要**写 `Math.atan2(dy, dx)`（那是瞄准）；
                 *    4 个方向就是 0 / 90 / 180 / 270 度，与玩家站哪儿无关。
                 * ⚠️ 子弹参数（速度 / 大小 / 伤害）仍走 `E.*`（照抄怪物 1 的那几个值）——
                 *    这样"怪物 3 的子弹和怪物 1 一样"是**自动成立**的，不用在这里写死数字。 */
                for (var q = 0; q < 4; q++) {
                    spawnEB(E.x, E.y, q * Math.PI / 2, E.bulletSpeed, E.bulletHalf);
                }
            }
            else if (E.spin) {
                /* ⭐⭐ **小怪 5「旋转」**（`0.3.1`）：**单发、固定 8 方向、顺时针** ✗。
                 * ⚠️ 与「十字」同一条规矩：**不读 `dx/dy`、不瞄准玩家** ✔ ——
                 *    角度只由"已经射了几发"决定 ✔。
                 * ⚠️ 屏幕坐标 y 向下 ⇒ 角度**递增**就是**顺时针** ✔：
                 *    `-90°`（正上 ✗）→ `-45°`（右上 ✗）→ `0°`（右 ✗）→ … → `-135°`（左上 ✗）→ 回到正上 ✔。
                 * ⚠️ 计数 `E.spinN` 在实例上（`makeOne` 初始化 ✗），只在这里自增 ✔。 */
                var sa = -Math.PI / 2 + E.spinN * (Math.PI / 4);
                spawnEB(E.x, E.y, sa, E.bulletSpeed, E.bulletHalf);
                E.spinN = (E.spinN + 1) % 8;
            }
            else {
                /* ⭐ **开火按种类来**：`count` 发、相邻夹角 `E.spread` 弧度，
                 *    关于瞄准方向**对称**（与 `ACTIVES[].spread` 同一套语义）。
                 *    `count:1` 时 `(i - (N-1)/2) * spread` = 0 ⇒ 与原来完全一样。
                 * ⚠️ 三发是**同帧全部射出**的散射，不是"连发三帧" —— 用户要的形态。 */
                var aim = Math.atan2(dy, dx);
                var n = E.count || 1, sp = E.spread || 0;
                for (var k = 0; k < n; k++) {
                    var nb2 = spawnEB(E.x, E.y, aim + (k - (n - 1) / 2) * sp, E.bulletSpeed, E.bulletHalf);
                    /* ⭐ 小怪 4「追踪」（`0.3.1`）：打上追踪标记 ✔（数值见 `EB_HOMING_*` ✗） */
                    if (nb2 && E.homing) nb2.homing = true;
                }
            }
            E.fireT = E.fireCd;
        }
        if (aabbOverlap(P, E) && P.inv <= 0) { hurtPlayer(E.contactDmg); }
        // 把玩家从敌人身上推开（只动玩家；各退一半会留稳定残留）
        pushApart(P, E);
        /* ⚠️ pushApart **可能把敌人顶进墙里**，而它是本帧最后一次改敌人位置 ——
         *    之后再没有和墙分离的机会。实测（一直按 S 贴着下边界压敌人）：
         *    敌人被顶到 y=708，而边界墙从 720 起，嵌入 **3.06px**
         *    （120 次随机压测里复现 5 次）。
         *    处理：被顶穿就退回它**最后一次确认合法的位置**，并在那里重新分离。
         *    若那个位置也进不去（玩家正好挡着），就保持原样 ——
         *    玩家自己造成的短暂挤压，比"瞬移脱困"更自然。 */
        if (worstPenetration(E, obs) > EPS) {
            escapeIfInside(E, { x: E.safeX, y: E.safeY }, obs);
            moveWithCollision(E, 0, 0, obs);
        }
        /* 维护"最后合法位置"（与玩家同样的做法）：
         * 敌人出生时给过 safeX/safeY，但**从来没人更新过**，
         * 所以脱困时它指向的永远是出生点 —— 那会让敌人瞬移回出生地。 */
        if (worstPenetration(E, obs) <= 0.01) { E.safeX = E.x; E.safeY = E.y; }
    }

    /* --- 玩家子弹 --- */
    for (i = Game.pbullets.length - 1; i >= 0; i--) {
        var b = Game.pbullets[i];
        /* ⭐ 被动 6「追踪弹」：**先转向、再位移**（见 `HOMING_TURN` 那段）。
         * ⚠️ 顺序不能反 —— 反了的话转向要到下一帧才生效，
         *    子弹"出膛那一帧"永远是直的，贴脸时看着像没追踪。 */
        if (b.home) {
            var homingTarget = nearestEnemyInCone(b.x, b.y, Math.atan2(b.vy, b.vx), HOMING_CONE);
            if (homingTarget) steerHomingBullet(b, homingTarget);
        }
        /* ⭐⭐ **环绕弹走单独一条路**（用户 2026-10-05 ✗）：位置 = 玩家当前位置 + 半径 × (cos,sin)
         *    ⇒ 跟着玩家走、自己转（每颗**各转各的** ⇒ 有子弹消失后不补空 ✗）。
         *    ⚠️ 下面两处判定对它**跳过**：**出界** ✗ 与**撞墙** ✗ —— "穿墙"是环绕弹的**特性** ✔
         *      （与技能 / BOSS1 那种圆形射出的**普通弹**不同 ✗，那些照旧撞墙 ✔）。
         *    命中敌人 / 抵消敌弹的判定**照旧**（作用不变 ✔）。⚠️ `P` 为 null 时清掉它 ✔。 */
        if (b.orbit) {
            if (!P) { Game.pbullets.splice(i, 1); continue; }
            /* ⚠️ **第一帧不推进**（`orbitFresh`）—— 否则首帧就偏 3° ✗（见施放段说明 ✔） */
            if (b.orbitFresh) b.orbitFresh = false; else b.orbitA += RING.omega;
            b.x = P.x + Math.cos(b.orbitA) * b.orbitR;
            b.y = P.y + Math.sin(b.orbitA) * b.orbitR;
            b.vx = -Math.sin(b.orbitA) * b.orbitR;   /* 仅供朝向/绘制参考，不参与位移 ✗ */
            b.vy = Math.cos(b.orbitA) * b.orbitR;
        } else {
            b.x += b.vx; b.y += b.vy;
        }
        /* ⚠️ 出界判定只对**普通弹**生效（环绕弹永远在玩家身边 ✔，不会出界 ✗） */
        if (!b.orbit && (b.x < -20 || b.x > LOGICAL_W + 20 || b.y < -20 || b.y > LOGICAL_H + 20)) { Game.pbullets.splice(i, 1); continue; }
        var gone = false;
        /* ⚠️ 撞墙只对**普通弹**生效；环绕弹忽略墙 ✔（"穿墙"是它的特性 ✗） */
        for (j = 0; !b.orbit && j < obs.length; j++) {
            /* 打墙：特效 = **子弹自己的大小 + 固定增量**（见 `pop` 的规则） */
            if (aabbRectMTV(b, obs[j])) { pop(b.x, b.y, PAL.hitPWall, b.half + BAL.player.hitGrowHalf); gone = true; break; }
        }
        if (gone) { Game.pbullets.splice(i, 1); continue; }
        for (j = Game.enemies.length - 1; j >= 0; j--) {
            var t = Game.enemies[j];
            if (aabbOverlap(t, b)) {
                t.hp -= b.dmg;
                onHitPassives();
                /* ⭐ 击中敌人：特效 = **子弹自己的大小 + 固定增量**（`hitGrowHalf`）。
                 *    ⚠️ 不是"扩到敌人那么大"（那会让每种子弹得到同一个尺寸，用户否过），
                 *      也不是比例（大子弹会胀得过大，用户也否过）。 */
                pop(b.x, b.y, PAL.hitPEnemy, b.half + BAL.player.hitGrowHalf);
                Game.pbullets.splice(i, 1);
                if (t.hp <= 0) {
                    Game.enemies.splice(j, 1);
                    /* ⚠️ 全部后果（计数 / 经验 / 金币 / 死亡特效）在 `killEnemy` 里
                     *    —— 别在这里展开，激光那边也要调它（见那里的说明）。 */
                    killEnemy(t);
                }
                break;
            }
        }
    }

    /* --- ⭐⭐ 激光（`0.2.0`）---
     *
     * ⚠️⚠️ **"帧伤"就是"每一帧都结算一次"**（用户明确说的"帧伤"）。
     *    所以这里**每帧**对激光带子里**所有**敌人各扣 `dmgPerFrame × 倍率` ——
     *    持续 10 帧 ⇒ 对同一只敌人总计 10 次。**它是穿透的**（用户定）：
     *    命中一只**不会**让激光停下或变短，带子里有几只就打几只。
     *
     * ⚠️ 方向、长度、**起点**都用放出那一帧存下的值
     *    （`P.laser.angle` / `.len` / `.ox` / `.oy`）——
     *    用户要求"放出后方向固定，不再因瞄准位置和玩家位置改变"，
     *    后来进一步要求**连起点也固定**（见 `castSkill` 里那段说明）。
     *    ⇒ 这里**不重算** `atan2`、**不重算** `laserReach`、**也不读 `P.x / P.y`**。
     *    ⚠️⚠️ 第一版这里传的是 `P.x, P.y` ⇒ 玩家一走，判定带子跟着平移，
     *      而渲染又把光束画在玩家身上 ⇒ 看着"激光跟着人走"。现在两处都读 `ox / oy`。
     *
     * ⚠️⚠️ **先收集、后结算**：`killEnemy` 之外还要 `splice` 掉死掉的敌人，
     *    而"边遍历边删数组"是经典 bug。所以按"先打伤害 → 再统一清理"两步走。
     *
     * ⚠️⚠️ **`frames > 0` 是"这一段还活着"的判据**（`0.2.0` 修，用户实测报的 bug）。
     *    用户原话：**"我感觉激光动画消失得比设置的帧数快"** —— 他说对了。
     *    原来这里没有这个判断，流程是"先打伤害 → 末尾递减 → 归零才置 null"：
     *      · 第 0 帧：判定 ✅、可见（alpha 1.00、frames 19）
     *      · ……
     *      · 第 18 帧：判定 ✅、可见（alpha 0.17、frames 1）
     *      · **第 19 帧：判定 ✅，但 `laserFade(0) = 0` ⇒ 光束画了却全透明**
     *      · 第 20 帧：`frames` 归零 ⇒ 置 null、不画
     *    ⇒ **判定 20 帧、可见只有 19 帧**（白占一帧在"看不见但还打人"上）。
     *    ⇒ 改成"**先判活、后递减**"：`frames > 0` 才打伤害 + 才画；
     *      `frames` 从 20 递减到 0 共 20 次、每次对应一帧 ⇒ **判定与可见都是 20 帧**。
     *    ⚠️ 副作用（好的）：**再也不存在"看不见却还在打人"的那一帧**。 */
    if (P.laser && P.laser.frames > 0) {
        var L = P.laser;
        var perFrame = LASER.dmgPerFrame * playerDamageMul();
        var dead = null;
        /* ⭐⭐⭐ **命中点动画**（`0.2.0`，用户要求"命中点产生动画，包括墙和敌人
         *   首次接触该道激光的地方"）。
         *
         * ## 做法
         * 先清空"这一帧的联系人"表，然后逐个命中点登记：
         *   · **敌人** —— 深度 `along`（沿光束的投影距离），key = 敌人对象
         *   · **墙**   —— 深度 = 光束长度 `len`（光束被墙截断，终点就是命中点），key = `'w'`
         * 登记时用 `laserContactNew(d, key)` 判断**是不是首次接触**：
         *   同一个 `d` 上一帧已经是同一个 `key` ⇒ 不重复冒；否则冒一簇火花。
         * ⇒ 观感 = "**光束扫到哪里、哪里第一次被打中就炸一下**"，
         *   墙和敌人一视同仁（这正是用户要的"命中点"）。
         * ⚠️⚠️ **必须"先清空、再逐帧重建"**：留着上一帧的条目，
         *    "首次接触"就永远判不出来（第二帧起全被当成"已经在冒"）。
         * ⚠️ 深度用**沿光束的投影距离**，天然从近到远排序
         *    ⇒ 同一只敌人被两道光束打时不会互相顶掉（不同光束各自有自己的表）。 */
        /* ⚠️⚠️ **两张表轮换**（不是"每帧清空"，见 `laserContactNew` 的说明）：
         *    交换之后 `laserContact` 是空的（这一帧重建）、`laserContactPrev`
         *    里是上一帧的记录 ⇒ `laserContactNew` 才比得出"首次接触"。 */
        var tmpC = Game.laserContactPrev;
        Game.laserContactPrev = Game.laserContact;
        Game.laserContact = tmpC;
        var i2;
        for (i2 in Game.laserContact) delete Game.laserContact[i2];
        var lc = Math.cos(L.angle), ls = Math.sin(L.angle);

        for (i = 0; i < Game.enemies.length; i++) {
            var lt = Game.enemies[i];
            if (lt.hp <= 0) continue;                       // 本帧刚被打死的，别重复计
            if (!laserHits(L.ox, L.oy, L.angle, L.len, LASER.halfWidth, lt)) continue;
            /* 命中点 = 敌人**朝向光束起点的那个边界点**（不是敌人中心）——
             * 中心点看着像"打在身体里"，边界点才是"打在表面上"。 */
            var dxe = lt.x - L.ox, dye = lt.y - L.oy;
            var alongE = dxe * lc + dye * ls;
            var hitX = L.ox + lc * (alongE - lt.half), hitY = L.oy + ls * (alongE - lt.half);
            /* ⚠️ key 传**敌人对象本身**（身份），**不是深度** —— 见 `laserContactNew`。
             * ⚠️ 配色：主闪 = `P_COLOR`（与子弹打中敌人同一色）、碎屑 = 它压暗一半。
             *    见 `LASER_SPARK_HIT` 那段说明。 */
            if (laserContactNew(lt)) {
                laserSparks(hitX, hitY, LASER_SPARK_HIT, dimHex(LASER_SPARK_HIT, LASER_SPARK_DIM), 'under', true);
            }
            lt.hp -= perFrame;
            onHitPassives();
            if (lt.hp <= 0) { if (!dead) dead = []; dead.push(lt); }
        }
        /* ⭐ **墙上的命中点**：光束被截断时，终点就落在墙里 —— 取它作为命中点。
         * ⚠️ 只在"真的被截断"时冒（`len < LASER.len` 才说明撞到了东西；
         *    没撞到的话终点在空处，不该冒火花）。 */
        if (L.len < LASER.len - 0.01) {
            var wx = L.ox + lc * L.len, wy = L.oy + ls * L.len;
            /* ⚠️ 墙用**灰**（与"打中敌人"的黄区分开）；碎屑同样是主闪压暗。 */
            if (laserContactNew('wall')) {
                laserSparks(wx, wy, LASER_SPARK_WALL, dimHex(LASER_SPARK_WALL, LASER_SPARK_DIM), 'under', true);
            }
        }
        if (dead) {
            for (i = 0; i < dead.length; i++) {
                var k = Game.enemies.indexOf(dead[i]);
                if (k < 0) continue;                        // 已经不在数组里（同帧被别的伤害收掉）
                Game.enemies.splice(k, 1);
                killEnemy(dead[i]);
            }
        }
        /* 倒计时。⚠️ 归零时置 `null`（而不是留个 `frames: 0`）——
         *    渲染与判定都靠 `if (P.laser)` 判断，留个 0 帧的对象会让它们
         *    各自都要记得再看一眼 `frames`，多一处能忘的地方。
         * ⚠️ 递减在**最后**：配合上面的 `frames > 0` 判据，
         *    `frames` 从 `LASER.frames` 走到 0 正好是 **`LASER.frames` 帧**
         *    （每一帧走一次这段），不多不少。 */
        L.frames--;
        if (L.frames <= 0) P.laser = null;
    }

    /* --- ⭐⭐ 环形护体：**打掉敌方子弹**（`0.2.1`）---
     *
     * 用户原话：**"把「环形护体」加强：对应的子弹碰到敌方子弹（包含普通/大，不包含激光）
     *    会与之抵消；两边子弹的动画都用碰到墙的"**。
     *
     * ⭐ 位置很讲究：**在玩家子弹之后、光束与敌弹之前**。
     *    · 在玩家子弹之后 ⇒ 这一帧已经走过位了，用的是"碰上了"的位置（不是上一帧的）；
     *    · 在敌弹之前 ⇒ 被抵消掉的敌弹**这一帧就不会再打到玩家**（否则先扣血再消失，
     *      "抵消"就成了"白挨一下"）。
     *
     * ⚠️⚠️ **只认 `b.blocks`**（只有环形护体传 `true`）—— 用户说的是那一招，
     *    不是"所有我方子弹都能挡弹"。普攻/点射/扇形**照旧直接穿过去**。
     * ⚠️ **不抵消光束**（`Game.beams` 根本不在这里）：用户明确"不包含激光"。
     *    ⇒ 也别为了"看起来统一"把光束搬进来判 —— 那是这一招的强度边界。
     * ⚠️ 特效**两边都用"撞墙"那一套**（用户原话）：
     *    · 我方：`'#ffffff'`（与玩家子弹撞墙逐字相同）
     *    · 敌方：`BAL.enemy.bulletColor`（与敌弹撞墙逐字相同）
     *    ⇒ 尺寸都用 `x.half + BAL.player.hitGrowHalf`（"子弹自己的大小 + 固定增量"，
     *      与撞墙/命中同一条规矩）。
     * ⚠️ 双方**一起消失**（"抵消"）—— 只删一边的话，敌弹还会继续飞。
     * ⚠️ **不受冻结影响**：这一段在冻结的闸门之前 ⇒ 冻住的敌弹照样会被打掉
     *    （"抵消"是两颗实体相撞，不是"敌人的动作"）。 */
    for (i = Game.pbullets.length - 1; i >= 0; i--) {
        var pb = Game.pbullets[i];
        if (!pb.blocks) continue;
        for (j = Game.ebullets.length - 1; j >= 0; j--) {
            var nb = Game.ebullets[j];
            if (!aabbOverlap(pb, nb)) continue;
            pop(pb.x, pb.y, PAL.hitPWall, pb.half + BAL.player.hitGrowHalf);
            pop(nb.x, nb.y, PAL.hitEWall, nb.half + BAL.player.hitGrowHalf);
            Game.pbullets.splice(i, 1);
            Game.ebullets.splice(j, 1);
            break;                        /* 这颗我方子弹已经没了 ⇒ 换下一颗 */
        }
    }

    /* --- BOSS2 的光束（`0.2.1`）---
     * ⭐ 放在敌方子弹**之前**：光束是"场地级"的持续伤害，
     *    先判它、再判子弹，同帧被两者打中时先扣光束那 3 点
     *    （无敌帧会让后面的那一下打不进来 —— 顺序影响"哪一下生效"，这里选了伤害高的）。
     * ⚠️ 判定与推进都在 `updateBeams` 里（含"警示期不判定"的规则）。
     * ⚠️⚠️ **冻结期整段跳过**（`0.2.1`，用户："子弹也一起冻结了(**包括boss2激光**)"）⇒
     *    警示 / 生效的倒计时都**不走**：警示期那道细红线会**停在原处继续闪**，
     *    生效期的粗束也停住（反正冻结期你也不会挨它的伤害）。
     *    ⚠️ 不跳过的话，冻住 3 秒里光束照样会走完自己的寿命 ⇒ "冻结"就漏了一样东西。 */
    if (Game.freeze <= 0) updateBeams(P);

    /* --- 敌人子弹 ---
     * ⚠️⚠️ **冻结期：敌弹停在原地**（`0.2.1`，用户："子弹也一起冻结了"）。
     *    做法是**跳过整段**（含出界/撞墙/命中判定）：它们既不动、也不消失，
     *    解冻后**从原地继续飞** —— 这才是"时间停止"的观感（而不是"子弹穿你而过"）。 */
    if (Game.freeze <= 0)
    for (i = Game.ebullets.length - 1; i >= 0; i--) {
        var eb = Game.ebullets[i];
        /* ⭐⭐ **追踪弹转向**（`0.3.1` 小怪 4 ✗）：先转向、再位移 ✔（与玩家那颗同一套 ✗）。
         *  ⚠️ 目标只有**玩家**（敌弹追玩家 ✗）；玩家不在了就直飞 ✔。
         *  ⚠️ 锥外**不追** ✔（与玩家那条一致 ✗）；速度大小保持不变 ✔。 */
        /* ⭐⭐ **BOSS4 招式 3 的公转大弹**（`0.3.1` ✗）：位置**不用速度** ✗，而由本体此刻的位置 +
         *    公转角 `orbitA` 直接摆 ✔（本体慢慢漂移 ⇒ 整圈跟着走 ✔）；摆在**最前面** ⇒ 天然跳过
         *    "直线位移 + 出界剔除 + 撞墙"（后两段在下面 ✗）✔。
         *  ⚠️ 存活用**自己的倒计时** `orbitT` ✗（`spawnEB` 造的弹没有 life 字段 ✔）⇒ 归零即移除 ✔。
         *  ⚠️ **抵消玩家子弹** ✗：与 `Game.bullets` 做 AABB ⇒ 命中删掉那颗玩家弹 + 火花 ✔；
         *     ⚠️ **不抵消激光** ✔（激光在 `Game.beams` ✗，与这里无关 ✔）；玩家的环绕弹不吃 ✔。
         *  ⚠️ 角速度 = `orbitSpeed` 弧度/秒 ÷ 60（每帧 ✗）≈ 126°/秒 ✔。 */
        if (eb.orbit && eb.orbitOwner) {
            /* ⭐⭐ **出生那一帧不自增** ✗（照玩家的环绕弹 ✔）⇒ 初相才能精确落在正上 ✔ */
            if (eb.orbitFresh) eb.orbitFresh = false; else eb.orbitA += BOSS4_SHOT.orbitSpeed / 60;
            eb.x = eb.orbitOwner.x + Math.cos(eb.orbitA) * BOSS4_SHOT.orbitR;
            eb.y = eb.orbitOwner.y + Math.sin(eb.orbitA) * BOSS4_SHOT.orbitR;
            eb.vx = 0; eb.vy = 0;
            /* ⚠️⚠️ 原来这里写的是"`orbitT` 归零就自灭"（300 帧 = 5 秒 ✗）—— **用户没要这个限制** ✗，
             *    实测表现为"下一轮放激光时旧环绕弹自己没了" ✔ ⇒ **已去掉** ✔。
             *    现在的存活规则 ✗：**被吃掉才消失**（抵消我方子弹 / 打中玩家 ✗）＋
             *    **下次再放这一招时替换旧的**（见 `boss4Orbit` ✗）＋ **本体死亡时清掉**（下面这行 ✔）。 */
            if (!eb.orbitOwner || eb.orbitOwner.hp <= 0 || eb.orbitOwner.dead) { Game.ebullets.splice(i, 1); continue; }
            /* ⭐⭐ **撞玩家：2 点伤害 + 自身消失**（用户 2026-10-05 ✗："也能对玩家造成2伤害(造成后也消失)" ✔）。
             *  ⚠️ 必须在这里**自己判** ✗ —— 本分支末尾 `continue` 会跳过循环后面那段"撞玩家"判定 ✔
             *     （我第一版就是这样 ⇒ 用户实测"碰玩家无事发生" ✔ ⇒ 已修 ✔）。
             *  ⚠️ 与后面那段同一套表现 ✗：出火花 + `hurtPlayer(eb.dmg)`（= 2 ✗）✔。 */
            if (P && aabbOverlap(P, eb)) {
                Game.ebullets.splice(i, 1);
                /* ⚠️⚠️ **照抄普通敌弹那套命中表现** ✗（见 2728 行 ✗）：`pop(eb.x, eb.y, PAL.hitEPlayer, half + hitGrowHalf)` ✔
                 *    ① 位置在**子弹处**（命中点 ✗），不是玩家身上 ✔（`hurtPlayer` 里明确"不弹红方块在玩家身上" ✔）；
                 *    ② **不能用 `laserSparks`** ✗ —— 我第一版写成激光那套 ⇒ 用户实测"**玩家反而多了被激光打到的动画**" ✔，
                 *       而**敌弹自己的消失动画反倒没出** ✗ ⇒ 现在两者都对了 ✔；
                 *    ③ 尺寸 = `half + hitGrowHalf`、颜色 `PAL.hitEPlayer`（红 = "我被打中了" ✗）✔。 */
                pop(eb.x, eb.y, PAL.hitEPlayer, eb.half + BAL.player.hitGrowHalf);
                /* ⚠️⚠️ **必须自己判无敌帧** ✗（用户 2026-10-05："似乎无视无敌帧" ✔）：
                 *    实测 `hurtPlayer` **自己不判 `inv`** ✗ —— 它只挡"冻结"（`Game.freeze > 0` ✗），
                 *    然后**无条件 `P.hp -= n` 并重设 `P.inv`** ✔ ⇒ **判无敌帧是调用方的事** ✗ ✔。
                 *    ⚠️ 与普通敌弹一致 ✗：无敌帧里**不扣血**、但**子弹照样被挡掉/消失** ✔
                 *       （见 2725 行的注释 ✗："不管这一下有没有真的扣血都弹" ✔）。 */
                if (P.inv <= 0) hurtPlayer(eb.dmg);
                continue;
            }
            /* ⭐⭐ **抵消我方子弹**（用户 2026-10-05 更正 ✗：**"敌方环绕弹应能抵消我方子弹（普通，大，我方环绕，但激光不行）
             *    （后消失）"** ✔）：⚠️ **不看 `blocks` 标记** ✗ —— 普通弹 / 大弹 / 我方环绕弹**一律**能抵消 ✔；
             *    ⚠️ **激光不在此列** ✔（激光在 `Game.beams` ✗，与 `Game.pbullets` 无关 ✔）。
             *  ⚠️ 抵消**双向** ✗：那颗我方子弹消失 ✔、**敌方环绕弹自己也消失** ✔（用户："（后消失）" ✔），
             *    并出两侧火花 ✔（与 2578 行那段 `blocks` 抵消同一套表现 ✗ —— 那段仍保留 ✔，它先跑 ✔）。 */
            var orbitHit = false;
            for (var bo = Game.pbullets.length - 1; bo >= 0; bo--) {
                var pb = Game.pbullets[bo];
                if (Math.abs(pb.x - eb.x) > pb.half + eb.half) continue;
                if (Math.abs(pb.y - eb.y) > pb.half + eb.half) continue;
                pop(pb.x, pb.y, PAL.hitPWall, pb.half + BAL.player.hitGrowHalf);
                pop(eb.x, eb.y, PAL.hitEWall, eb.half + BAL.player.hitGrowHalf);
                Game.pbullets.splice(bo, 1);
                Game.ebullets.splice(i, 1);          /* ⭐ 敌方环绕弹**也消失** ✔ */
                orbitHit = true;
                break;
            }
            if (orbitHit) continue;                  /* ⚠️ 这颗敌弹已经没了 ⇒ 后面的位移/剔除/撞墙/撞玩家都别再走 ✔ */
            continue;                                          /* ⚠️ 后面那几段（位移/剔除/撞墙）都不参与 ✔ */
        }
        if (eb.homing && P) {
            var ta = Math.atan2(P.y - eb.y, P.x - eb.x);
            var ca = Math.atan2(eb.vy, eb.vx);
            var df = ta - ca;
            while (df > Math.PI) df -= Math.PI * 2;
            while (df < -Math.PI) df += Math.PI * 2;
            if (df <= EB_HOMING_CONE && df >= -EB_HOMING_CONE) {
                if (df > EB_HOMING_TURN) df = EB_HOMING_TURN;
                else if (df < -EB_HOMING_TURN) df = -EB_HOMING_TURN;
                var spd = Math.sqrt(eb.vx * eb.vx + eb.vy * eb.vy);
                ca += df;
                eb.vx = Math.cos(ca) * spd; eb.vy = Math.sin(ca) * spd;
            }
        }
        eb.x += eb.vx; eb.y += eb.vy;
        if (eb.x < -20 || eb.x > LOGICAL_W + 20 || eb.y < -20 || eb.y > LOGICAL_H + 20) { Game.ebullets.splice(i, 1); continue; }
        var blocked = false;
        for (j = 0; j < obs.length; j++) {
            if (aabbRectMTV(eb, obs[j])) { blocked = true; break; }
        }
        /* ⚠️ 撞墙也要弹命中特效，和主角子弹撞墙（上面那段）保持一致 ——
         *    以前这里**静默消失**，敌人子弹打到墙上什么反馈都没有。
         *    颜色用 `EB_COLOR`（子弹自己的颜色），不用默认白色：
         *    墙是 `#3a3f46` 深灰，白点在墙上对比太强、看着像主角打出来的。 */
        /* 敌人子弹撞墙：同样按"子弹大小 + 固定增量"（与玩家子弹同一套规则） */
        if (blocked) { pop(eb.x, eb.y, PAL.hitEWall, eb.half + BAL.player.hitGrowHalf); Game.ebullets.splice(i, 1); continue; }
        if (aabbOverlap(P, eb)) {
            Game.ebullets.splice(i, 1);
            /* ⭐⭐ **打中玩家的命中动画**（`0.2.0`，用户要求"敌方子弹打到玩家缺少对应动画"）。
             *
             * 用户补了一句：**"有类似玩家打中敌人的动画就行了，不加碎屑"**
             *    ⇒ 就是**一个 `pop`**，与玩家打中敌人**同一套规则**：
             *      尺寸 = `子弹 half + hitGrowHalf`（加法增量）、持续 12 帧、无碎屑。
             * ⚠️ **颜色用 `PLAYER_HURT`（红），不是 `P_COLOR`（黄）** ——
             *    黄是"我打中了"，红是"我被打中了"；见 `PLAYER_HURT` 那段说明。
             * ⚠️⚠️ **画在子弹位置（命中点），不是 `P.x, P.y`** ——
             *    `hurtPlayer` 里明确写了"不弹红方块在玩家身上"（用户定过：
             *    "玩家受伤时不要变成红色，会混淆"）。玩家身上的表达仍然只有无敌帧闪烁。
             * ⚠️ **不管这一下有没有真的扣血都弹**（`P.inv > 0` 时也一样）：
             *    无敌帧里子弹照样被挡掉、照样消失，那一下"打中了但没伤到我"也该有反馈，
             *    否则玩家会以为子弹穿过去了。 */
            pop(eb.x, eb.y, PAL.hitEPlayer, eb.half + BAL.player.hitGrowHalf);
            /* ⭐ **伤害跟着子弹走**（`0.2.0`）：小怪子弹 `dmg = 1`、BOSS 散射是 `2`。
             * ⚠️ 这里**不能写死 1** —— 那样"给某种子弹加伤害"就必须来改这一行，
             *    而子弹的伤害明明是它自己的属性（`spawnEB` 的第 6 个参数）。
             * ⚠️ 无敌帧仍然只在 `P.inv <= 0` 时才结算（同帧多发只算一次）。 */
            if (P.inv <= 0) hurtPlayer(eb.dmg || 1);
        }
    }

    /* --- 收尾：敌人可能把玩家顶进墙里 → 先做一次分离，再兜底脱困 --- */
    separateFromRects(P, obs, false);
    escapeIfInside(P, { x: P.safeX, y: P.safeY }, obs);

    /* --- 特效 ---
     * ⭐⭐ **就是"每帧缩一点"，没有别的机制**（`0.2.0` 第四版定稿）。
     *
     * 这里来回改过三次，全都是想"让爆炸活到结算框弹出"（全被用户否掉）：
     *   ① 判出胜负就跳过这段 ⇒ 缩到一半卡住
     *   ② `hold` 设成 resultDelay ⇒ **每个**敌人都僵 0.6 秒
     *   ③ 短 hold + 结算时锁回满尺寸 ⇒ **最后一个**敌人满尺寸僵 0.6 秒
     * 真凶其实是**上面那个 `if (Game.resultPending) return`** —— 特效循环写在它后面，
     * 永远跑不到，`t` 一帧都不变。所以那三版怎么调参数都没用。
     *
     * **定稿规则（一句话判据）**：
     *   > 特效永远按自己的生命周期走；结算延迟**只延迟弹窗**，不改变任何动画。
     *
     * ⚠️ 所以这里**不要**再写 `if (decided)` / `locked` / `hold` 之类的分支或字段。
     * ⚠️ `update()` 提前 `return` 不是"特效必须停下"的理由 —— 特效跑在 `return` 之前。 */
    for (i = Game.fx.length - 1; i >= 0; i--) {
        if (--Game.fx[i].t <= 0) Game.fx.splice(i, 1);
    }
    /* ⚠️ 激光命中点的火花同理，必须在同一处递减（`laserSparks` 只负责"生"）。
     *    粒子会飞散 ⇒ 位置也要在这里推进。 */
    for (i = Game.sparks.length - 1; i >= 0; i--) {
        var sk = Game.sparks[i];
        sk.x += sk.vx; sk.y += sk.vy;
        sk.vx *= 0.86; sk.vy *= 0.86;          /* 阻尼：飞出去就慢下来 */
        if (--sk.t <= 0) Game.sparks.splice(i, 1);
    }

    /* --- 胜负 ---
     * 测试关（win:'never'）不判定通关：清光怪物也不结束，
     * 这样碰撞测试不会因为"怪都被打死了"而中断。
     * ⭐ 判出来之后**不立刻结算**，而是进入 `BAL.resultDelay` 帧的倒计时
     *    （见 update() 开头那一段）—— 用户要求延迟一个固定时间再弹结算框。
     * ⚠️ 本帧已经判出胜负时**不冻结特效**（`0.2.0` 第四版）：特效永远按自己的
     *    生命周期走，结算延迟只延迟弹窗。（前三次全错在"想让爆炸活到弹窗"。） */
    var winRule = currentLevel().win;
    /* ⚠️ 两个分支都带 `!Game.resultPending` 守卫：一旦进入倒计时就**不再重设**，
     *    否则倒计时每帧都被重置、永远走不完（胜负早已判定，不该再翻）。
     * ⚠️ 血掉光的分支还要带 `!Game.playerDead`：死亡是**不可逆**的，
     *    别让它每帧重复置位（那样死亡动画会被反复重启、永远缩不完）。 */
    if (P.hp <= 0) {
        P.hp = 0;
        if (!Game.playerDead) {
            /* ⭐ 死亡：起一段渐缩动画 + 记下"这个人已经死了"（持久，见 startLevel 复位） */
            Game.playerDead = true;
            Game.playerDeathT = BAL.deathFrames;
        }
        if (!Game.resultPending) Game.resultPending = { t: BAL.resultDelay, win: false };
    } else if (winRule !== 'never' && requiredLeft() === 0 &&
               !Game.resultPending && !Game.wavePending) {
        /* ⭐⭐ **还有下一波 ⇒ 这一关不算完**（`0.2.1`）：
         *    起一段 `BAL.resultDelay` 帧的倒计时，到点放下一波（见 update() 开头）。
         *    ⚠️ 守卫里的 `!Game.wavePending` 有两个作用：
         *      ① 倒计时**只起一次**（否则每帧重设 ⇒ 永远走不完，与 `resultPending` 同一个坑）；
         *      ② 倒计时期间**不重复判**（这一帧场上没敌人是正常的，不是"打完了"）。 */
        if (Game.wave + 1 < Game.waveTotal) {
            Game.wavePending = { t: BAL.resultDelay };
        } else {
            Game.resultPending = { t: BAL.resultDelay, win: true };
        }
    }

    /* --- 碰撞一致性检查（ghost collision 哨兵） --- */
    COLCHECK.tick();
    HUD.sync();          // 关卡内 HUD（DOM，只在变化时写）
}

